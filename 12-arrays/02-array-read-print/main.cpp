// -----------------------------------------------------------------------------
// این فایل یک مثال آموزشی برای «آرایه‌های یک‌بعدی» در زبان ++C است.
//
// در این مثال:
// - یک آرایه با اندازه 15 تعریف می‌شود.
// - کاربر باید 15 عدد وارد کند تا در خانه‌های آرایه ذخیره شوند.
// - سپس برنامه تمام عناصر آرایه را به همان ترتیبی که وارد شده‌اند چاپ می‌کند.
//
// هدف آموزشی این مثال:
// - آشنایی دانشجو با تعریف آرایه ثابت (const int NUMBER)
// - استفاده از حلقه for برای ورود اطلاعات به آرایه
// - استفاده از حلقه for برای چاپ عناصر آرایه
// - درک مفهوم اندیس‌گذاری (indexing) عناصر آرایه
//
// این فایل برای تمرین مقدماتی مبحث آرایه‌ها در درس برنامه‌نویسی ارائه شده است.
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    const int NUMBER = 15;

    int x[NUMBER];

    // گرفتن ۱۵ ورودی و قرار دادن آن‌ها در خانه‌های آرایه
    for (int i = 0; i < NUMBER; i = i + 1)
    {
        cout << "Enter number" << (i + 1) << ": ";
        cin >> x[i];
    }

    // چاپ عناصر آرایه
    for (int i = 0; i < NUMBER; i = i + 1)
    {
        cout << x[i] << ",";
    }

    return 0;
}

// -----------------------------------------------------------------------------
// این برنامه یک مثال آموزشی از کار با آرایه‌های یک‌بعدی در ++C است.
//
// هدف این مثال:
// - تعریف آرایه ثابت با استفاده از const int
// - محاسبه‌ی مجموع عناصر آرایه با استفاده از حلقه for
// - محاسبه‌ی میانگین عناصر با تقسیم مجموع بر تعداد اعضا
// - آشنایی با نوع داده double برای جلوگیری از خطای محاسباتی در میانگین
//
// شرح عملکرد برنامه:
// 1. آرایه‌ای به نام x شامل 4 عدد تعریف شده است:  {5, 8, 2, 4}
// 2. یک متغیر s از نوع double برای ذخیره مجموع عناصر ساخته می‌شود.
// 3. در حلقه‌ی for هر عنصر آرایه به s اضافه می‌شود.
// 4. مجموع عناصر چاپ می‌شود.
// 5. میانگین از طریق s / NUM محاسبه و چاپ می‌شود.
//
// این مثال از تمرین‌های مقدماتی برای درس برنامه‌نویسی است و پایه‌ای برای
// تمرین‌های پیشرفته‌تر مانند یافتن بیشینه، کمینه، و تحلیل آماری روی آرایه‌هاست.
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{

    const int NUM = 4;
    int x[NUM] = {5, 8, 2, 4};

    double s = 0;
    for (int i = 0; i < NUM; i = i + 1)
    {
        s = s + x[i];
    }

    cout << "Sum is: " << s << "\n";
    cout << "Avg is: " << s / NUM << "\n";

    return 0;
}

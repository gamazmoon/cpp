// -----------------------------------------------------------------------------
// این برنامه یک مثال آموزشی برای یافتن «بیشترین مقدار» (Maximum) در آرایه
// در زبان ++C است.
//
// هدف آموزشی این مثال:
// - آشنایی با الگوریتم پیدا کردن بیشینه در یک آرایه
// - درک این نکته که مقدار اولیه‌ی max باید برابر اولین عنصر آرایه باشد
// - استفاده از حلقه for برای پیمایش تمام عناصر
// - مقایسه عناصر با max و به‌روزرسانی مقدار آن در صورت یافتن مقدار بزرگ‌تر
//
// شرح عملکرد برنامه:
// 1. آرایه x با 4 مقدار اولیه:  {5, 8, 2, 4}
// 2. مقدار max برابر اولین عنصر آرایه قرار می‌گیرد.
// 3. در حلقه for تک‌تک عناصر بررسی می‌شوند:
//      اگر x[i] بزرگ‌تر از max باشد، مقدار max به x[i] تغییر می‌کند.
// 4. در پایان مقدار بیشینه چاپ می‌شود.
//
// این مثال پایه‌ای برای تمرین‌های پیشرفته‌تر مانند یافتن کمینه، یافتن
// دومین بیشینه، و تحلیل آماری آرایه است.
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    const int NUM = 4;
    int x[NUM] = {5, 8, 2, 4};

    int max = x[0];
    for (int i = 0; i < NUM; i = i + 1)
    {
        if (max < x[i])
        {
            max = x[i];
        }
    }

    cout << "Max is: " << max << "\n";

    return 0;
}

// -----------------------------------------------------------------------------
// این برنامه یک مثال بسیار ساده برای آشنایی با نحوه‌ی تعریف و مقداردهی آرایه‌ها
// در زبان ++C است.
//
// در این مثال:
// 1. یک آرایه 5 عضوی از نوع int تعریف شده و در همان ابتدا با مقدار صفر مقداردهی شده است.
//      int x[5] = {0, 0, 0, 0, 0};
//
// 2. سپس هر خانه‌ی آرایه به صورت جداگانه دوباره مقداردهی می‌شود:
//      x[0] = 0;
//      ...
//
// 3. در نهایت با استفاده از یک حلقه for تمام عناصر آرایه مقداردهی می‌شوند:
//      for (int i = 0; i < 5; i++)
//          x[i] = 0;
//
// هدف این مثال:
// - نشان دادن چند روش مختلف برای مقداردهی آرایه
// - مقایسه مقداردهی اولیه، مقداردهی خانه به خانه، و مقداردهی با استفاده از حلقه
// - کمک به دانشجو برای درک بهتر اینکه چرا استفاده از حلقه روشی ساده‌تر و قابل گسترش‌تر است.
//
// این تمرین معمولاً در ابتدای آموزش آرایه‌ها ارائه می‌شود تا دانشجو با مفهوم
// index و مقداردهی چندباره آشنا شود و تفاوت روش‌ها را ببیند.
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    int x[5] = {0, 0, 0, 0, 0};
    x[0] = 0;
    x[1] = 0;
    x[2] = 0;
    x[3] = 0;
    x[4] = 0;

    for (int i = 0; i < 5; i = i + 1)
    {
        x[i] = 0;
    }

    return 0;
}

// -----------------------------------------------------------------------------
// این برنامه یک مثال آموزشی برای «جستجوی خطی» (Linear Search) در آرایه
// در زبان ++C است.
//
// هدف آموزشی این مثال:
// - آشنایی با مفهوم جستجو در آرایه
// - یادگیری الگوریتم جستجوی خطی یا Linear Search
// - استفاده از متغیر key برای مشخص کردن مقدار مورد جستجو
// - استفاده از متغیر index برای نگهداری محل پیدا شدن مقدار
// - استفاده از مقدار اولیه -1 برای نشان دادن حالت «پیدا نشدن»
// - استفاده از دستور break برای متوقف کردن حلقه پس از یافتن مقدار
//
// شرح عملکرد برنامه:
// 1. آرایه‌ای به نام x با 4 مقدار اولیه تعریف شده است:
//      {5, 8, 2, 4}
//
// 2. مقدار key برابر 8 است.
//    یعنی برنامه می‌خواهد عدد 8 را در آرایه پیدا کند.
//
// 3. متغیر index ابتدا برابر -1 قرار داده می‌شود.
//    این مقدار یعنی هنوز عدد مورد نظر پیدا نشده است.
//
// 4. حلقه for عناصر آرایه را از ابتدا تا انتها بررسی می‌کند.
//    اگر مقدار x[i] برابر key باشد:
//      - مقدار i در index ذخیره می‌شود.
//      - با دستور break حلقه متوقف می‌شود.
//
// 5. پس از پایان حلقه:
//      - اگر index همچنان -1 باشد، یعنی عدد پیدا نشده است.
//      - در غیر این صورت، محل پیدا شدن عدد چاپ می‌شود.
//
// نکته آموزشی:
// اندیس آرایه‌ها در ++C از صفر شروع می‌شود.
// بنابراین اگر عددی در اولین خانه آرایه باشد، index آن برابر 0 است.
//
// این مثال پایه‌ای برای تمرین‌های پیشرفته‌تر مانند شمارش تعداد تکرار یک مقدار،
// جستجوی آخرین موقعیت یک مقدار، و جستجو در داده‌های دانشجویی است.
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    const int NUM = 4;
    int x[NUM] = {5, 8, 2, 4};

    const int key = 8;

    int index = -1;
    for (int i = 0; i < NUM; i = i + 1)
    {
        if (x[i] == key)
        {
            index = i;
            break;
        }
    }

    if (index == -1)
    {
        cout << "Not found";
    }
    else
    {
        cout << "Found in: " << index;
    }

    return 0;
}

// -----------------------------------------------------------------------------
// محاسبه مجموع و میانگین عناصر آرایه دوبعدی در ++C
// این برنامه یک مثال آموزشی برای کار با «آرایه‌های دوبعدی» در ++C است.
// در این مثال مجموع و میانگین تمام عناصر یک آرایه دوبعدی محاسبه می‌شود.
//
// هدف آموزشی مثال:
// - آشنایی با مقداردهی اولیه آرایه دوبعدی
// - استفاده از حلقه‌های تو در تو برای پیمایش آرایه
// - محاسبه مجموع عناصر آرایه
// - محاسبه میانگین عناصر
//
// شرح عملکرد برنامه:
//
// 1. یک آرایه دوبعدی x با 2 سطر و 3 ستون تعریف و مقداردهی اولیه شده است:
//
//      {10, 11, 12}
//      {20, 21, 22}
//
// 2. دو متغیر i و j برای پیمایش سطرها و ستون‌ها استفاده می‌شوند.
//
// 3. متغیر sum برای نگهداری مجموع عناصر تعریف شده و مقدار اولیه آن صفر است.
//
// 4. با استفاده از دو حلقه for تو در تو:
//      - همه عناصر آرایه بررسی می‌شوند.
//      - مقدار هر خانه به sum اضافه می‌شود.
//
// 5. پس از پایان حلقه‌ها:
//      - مجموع عناصر چاپ می‌شود.
//      - میانگین عناصر نیز محاسبه و چاپ می‌شود.
//
// فرمول میانگین:
//
//      Average = Sum / Number of Elements
//
// در این مثال تعداد عناصر برابر است با:
//
//      2 × 3 = 6
//
// نکات آموزشی:
// - برای پیمایش آرایه‌های دوبعدی معمولاً از حلقه‌های تو در تو استفاده می‌شود.
// - متغیر sum باید قبل از شروع جمع کردن مقداردهی اولیه شود.
// - تعداد کل عناصر آرایه برابر حاصل‌ضرب تعداد سطرها در تعداد ستون‌ها است.
//
// این مثال پایه‌ای برای تمرین‌های پیشرفته‌تر مانند:
// - محاسبه میانگین هر سطر
// - محاسبه میانگین هر ستون
// - پیدا کردن بزرگ‌ترین یا کوچک‌ترین مقدار در ماتریس
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{

    int x[2][3] = {
        {8, 4, 12},
        {10, 6, 9}};

    int j, i;

    int sum = 0;
    for (j = 0; j < 2; j = j + 1)
    {
        for (i = 0; i < 3; i = i + 1)
        {
            sum = sum + x[j][i];
        }
    }

    cout << "Sum is:" << sum << "\n";
    cout << "Avg is:" << sum / (2 * 3) << "\n";

    return 0;
}

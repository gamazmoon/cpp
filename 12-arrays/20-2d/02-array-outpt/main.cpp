// -----------------------------------------------------------------------------
// مثال نسبت‌دهی (مقداردهی اولیه) آرایه یک‌بعدی و دوبعدی
// این برنامه یک مثال آموزشی برای «نسبت‌دهی» یا «مقداردهی اولیه» آرایه‌ها
// در زبان ++C است.
//
// هدف آموزشی مثال:
// - آشنایی با مقداردهی اولیه آرایه یک‌بعدی
// - آشنایی با مقداردهی اولیه آرایه دوبعدی
// - تفاوت بین آرایه‌های مقداردهی‌شده و آرایه‌هایی که باید ورودی بگیرند
// - نمایش مقادیر آرایه دوبعدی پس از نسبت‌دهی اولیه
//
// شرح عملکرد برنامه:
//
// 1. در ابتدا یک آرایه یک‌بعدی تعریف و مقداردهی شده است:
//
//        int a[4] = {17, 2, 12, 4};
//
//    این شیوه مقداردهی اولیه (Initialization) نام دارد و هنگام تعریف آرایه
//    انجام می‌شود. این آرایه نیازی به cin ندارد.
//
// 2. سپس یک آرایه دوبعدی 2×3 نیز مقداردهی اولیه شده:
//
//        {10, 11, 12}
//        {20, 21, 22}
//
//    این آرایه نیز بدون دریافت ورودی از کاربر، دارای مقدارهای مشخص است.
//
// 3. با استفاده از دو حلقه for تو در تو، مقادیر آرایه دوبعدی نمایش داده می‌شود.
//    (آرایه یک‌بعدی در این مثال فقط برای نشان دادن روش مقداردهی اولیه تعریف شده است.)
//
// نکات آموزشی:
// - مقداردهی اولیه فقط هنگام تعریف آرایه قابل انجام است.
// - در مقداردهی اولیه، تعداد عناصر باید با ظرفیت آرایه هماهنگ باشد.
// - آرایه‌های چندبعدی نیز مانند آرایه‌های یک‌بعدی می‌توانند مقداردهی اولیه شوند.
//
// این مثال پایه‌ای برای مباحث بعدی مانند:
// - مقداردهی اولیه آرایه‌های بزرگ‌تر
// - تفاوت بین مقداردهی اولیه و نسبت‌دهی در زمان اجرا
// - کار با ماتریس‌ها
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{

    int x[2][3] = {
        {8, 4, 12},
        {10, 6, 9}};

    cout << x[0][0] << " ";
    cout << x[0][1] << " ";
    cout << x[0][2] << " ";

    cout << "\n";

    cout << x[1][0] << " ";
    cout << x[1][1] << " ";
    cout << x[1][2] << " ";

    return 0;
}

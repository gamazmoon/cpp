// -----------------------------------------------------------------------------
// مثال نمایش یک سطر خاص از آرایه دوبعدی
// این برنامه یک مثال آموزشی برای «دسترسی و نمایش یک سطر خاص» از آرایه دوبعدی
// در زبان ++C است.
//
// هدف آموزشی مثال:
// - درک این مطلب که یک آرایه دوبعدی مجموعه‌ای از سطرهاست.
// - یادگیری نحوه دسترسی به تمام ستون‌های یک سطر خاص (بدون نیاز به دو حلقه).
// - آشنایی با تفاوت پیمایش کل ماتریس و پیمایش یک ردیف مجزا.
//
// شرح عملکرد برنامه:
//
// 1. یک آرایه دوبعدی 2 در 3 تعریف و مقداردهی شده است:
//    سطر اول (اندیس 0): {10, 11, 12}
//    سطر دوم (اندیس 1): {20, 21, 22}
//
// 2. برخلاف مثال‌های قبل که از دو حلقه for استفاده می‌شد، در اینجا فقط یک حلقه
//    برای متغیر j (ستون‌ها) تعریف شده است.
//
// 3. در دستور خروجی، اندیس سطر ثابت نگه داشته شده است:
//
//        cout << x[1][j] << "\t";
//
//    در اینجا عدد 1 نشان‌دهنده‌ی سطر دوم آرایه است. بنابراین با تغییر j از 0 تا 2،
//    فقط مقادیر سطر دوم (یعنی 20، 21 و 22) چاپ می‌شوند.
//
// نکات آموزشی:
// - برای دسترسی به یک سطر خاص، اندیس سطر را ثابت و اندیس ستون را متغیر می‌گذاریم.
// - اندیس 1 در آرایه‌ها به معنای ردیف «دوم» است (چون شمارش از صفر شروع می‌شود).
// - این تکنیک زمانی کاربرد دارد که بخواهیم عملیاتی را فقط روی یک بخش خاص از ماتریس
//   (مثلاً فقط یک سطر یا فقط یک ستون) انجام دهیم.
//
// این مثال پایه‌ای برای مباحث بعدی مانند:
// - محاسبه مجموع یک سطر خاص از ماتریس
// - جابجا کردن دو سطر با یکدیگر
// - کپی کردن یک سطر در یک آرایه یک‌بعدی
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{

    int x[2][3] = {
        {10, 11, 12},
        {20, 21, 22}
    };

    int j;

    // پیمایش ستون‌ها برای سطر دوم (اندیس 1)
    for (j = 0; j < 3; j = j + 1)
    {
        cout << x[1][j] << "\t";
    }

    cout << endl; // رفتن به خط بعد

    return 0;
}

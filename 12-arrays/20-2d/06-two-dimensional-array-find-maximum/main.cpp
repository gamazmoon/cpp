// -----------------------------------------------------------------------------
// مثال پیدا کردن بزرگ‌ترین مقدار در آرایه دوبعدی
// این برنامه یک مثال آموزشی برای «پیدا کردن بزرگ‌ترین مقدار» در آرایه دوبعدی
// در زبان ++C است.
//
// هدف آموزشی مثال:
// - یادگیری روش جستجوی مقدار بیشینه (Maximum) در آرایه دوبعدی
// - استفاده از حلقه‌های تو در تو برای پیمایش تمام عناصر آرایه
// - ذخیره‌ی اندیس (سطر و ستون) محل یافتن بزرگ‌ترین مقدار
// - استفاده از متغیر کمکی برای مقایسه و به‌روزرسانی مقدار بیشینه
//
// شرح عملکرد برنامه:
//
// 1. آرایه دوبعدی x با 2 سطر و 3 ستون ساخته و مقداردهی اولیه شده است:
//
//        {10, 11, 12}
//        {20, 21, 22}
//
// 2. متغیرهای indI و indJ برای نگهداری موقعیت عنصر بیشینه در آرایه هستند.
//    مقدار اولیه‌ی هر دو متغیر صفر است (یعنی فرض می‌کنیم بیشینه اولیه در x[0][0] قرار دارد).
//
// 3. متغیر max نیز با مقدار اولین خانه آرایه مقداردهی شده است:
//        max = x[0][0];
//
// 4. با استفاده از دو حلقه for تو در تو:
//        - تمام عناصر آرایه بررسی می‌شوند.
//        - اگر عنصری بزرگ‌تر از max باشد، مقدار آن در max ذخیره می‌شود
//          و موقعیت آن در indI و indJ ثبت می‌گردد.
//
// 5. در پایان برنامه:
//        - بیشترین مقدار در متغیر max ذخیره شده است.
//        - موقعیت آن به صورت (سطر، ستون) چاپ می‌شود.
//
// نکات آموزشی:
// - اندیس آرایه‌ها از صفر شروع می‌شود، بنابراین خانه‌ی اول (0,0) است.
// - هنگام مقایسه باید از مقدار اولین عنصر به عنوان نقطه‌ی شروع استفاده کنیم.
// - نگهداری محل عنصر بیشینه (با indI و indJ) بسیار مفید است.
//
// این مثال پایه‌ای برای برنامه‌های پیشرفته‌تر مانند:
// - پیدا کردن کوچک‌ترین مقدار (Minimum) در آرایه دوبعدی
// - یافتن موقعیت عناصر خاص بر اساس شرط
// - بررسی بیشینه‌ی هر سطر یا هر ستون جداگانه
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{

    int x[2][3] = {
        {10, 11, 12},
        {20, 21, 22}};

    int i, j;

    int indI = 0;
    int indJ = 0;
    int max = x[0][0];
    
    for (i = 0; i < 2; i = i + 1)
    {
        for (j = 0; j < 3; j = j + 1)
        {
            if (x[i][j] > max)
            {
                max = x[i][j];
                indI = i;
                indJ = j;
            }
        }
    }

    cout << "Max in (" << indI << "," << indJ << ")" << endl;
    cout << "Max is:" << max;

    return 0;
}

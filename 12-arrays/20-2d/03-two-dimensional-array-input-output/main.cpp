// -----------------------------------------------------------------------------
// مثال ورود و نمایش آرایه دوبعدی در ++C
// این برنامه یک مثال آموزشی برای «آرایه‌های دوبعدی» (Two-Dimensional Arrays)
// در زبان ++C است.
//
// هدف آموزشی این مثال:
// - آشنایی با مفهوم آرایه دوبعدی
// - یادگیری نحوه تعریف آرایه دو بعدی
// - تمرین استفاده از حلقه‌های تو در تو (Nested Loops)
// - دریافت مقادیر آرایه از ورودی (cin)
// - نمایش مقادیر آرایه در قالب جدول
//
// شرح عملکرد برنامه:
// 1. یک آرایه دوبعدی x با 2 سطر و 3 ستون تعریف شده است.
//      int x[2][3];
//
// 2. دو متغیر i و j برای پیمایش سطرها و ستون‌ها استفاده می‌شود.
//
// 3. در بخش اول برنامه:
//    - با استفاده از دو حلقه for تو در تو،
//      مقادیر آرایه از کاربر دریافت می‌شود.
//    - کاربر برای هر خانه آرایه یک عدد وارد می‌کند.
//
// 4. در بخش دوم برنامه:
//    - دوباره با دو حلقه for تو در تو،
//      مقادیر ذخیره‌شده در آرایه چاپ می‌شود.
//    - دستور '\t' باعث می‌شود خروجی به صورت جدولی نمایش داده شود.
//
// نکات آموزشی:
// - اندیس آرایه‌ها در ++C از صفر شروع می‌شود.
// - x[0][0] اولین عنصر و x[1][2] آخرین عنصر این آرایه است.
// - استفاده از حلقه‌های تو در تو برای کار با آرایه‌های چندبعدی ضروری است.
//
// این مثال پایه‌ای برای تمرین‌های پیشرفته‌تر مانند:
// - جمع عناصر هر سطر یا ستون
// - پیدا کردن بزرگ‌ترین یا کوچک‌ترین مقدار
// - کار با ماتریس‌ها در برنامه‌نویسی
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{

    int x[2][3];
    int j, i;

    for (j = 0; j < 2; j = j + 1)
    {
        for (i = 0; i < 3; i = i + 1)
        {
            cout << "Please enter (" << j + 1 << "," << i + 1 << "): ";
            cin >> x[j][i];
        }
    }

    for (j = 0; j < 2; j = j + 1)
    {
        for (i = 0; i < 3; i = i + 1)
        {
            cout << x[j][i] << "\t";
        }
        cout << "\n";
    }

    return 0;
}

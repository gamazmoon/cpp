// -----------------------------------------------------------------------------
// مثال نمایش یک ستون خاص از آرایه دوبعدی
// این برنامه یک مثال آموزشی برای «نمایش یک ستون خاص» از آرایه دوبعدی
// در زبان ++C است.
//
// هدف آموزشی مثال:
// - یادگیری نحوه دسترسی به یک ستون خاص در آرایه دوبعدی
// - درک نحوه تغییر اندیس سطر در حالی که اندیس ستون ثابت است
// - آشنایی با پیمایش عمودی در ماتریس
//
// شرح عملکرد برنامه:
//
// 1. یک آرایه دوبعدی با 2 سطر و 3 ستون تعریف و مقداردهی اولیه شده است:
//
//        {10, 11, 12}
//        {20, 21, 22}
//
// 2. در این مثال هدف نمایش ستون سوم آرایه است.
//
// 3. برای این کار:
//    - اندیس ستون ثابت نگه داشته شده است (عدد 2)
//    - اندیس سطر با استفاده از حلقه for تغییر می‌کند.
//
//        cout << x[i][2] << "\t";
//
// 4. با تغییر i از 0 تا 1، عناصر ستون سوم چاپ می‌شوند:
//
//        12
//        22
//
// نکات آموزشی:
// - برای دسترسی به یک ستون خاص، اندیس ستون ثابت و اندیس سطر متغیر است.
// - اندیس ستون 2 به معنای ستون سوم است، زیرا شمارش آرایه‌ها از صفر شروع می‌شود.
// - این روش برای انجام عملیات روی ستون‌های ماتریس بسیار کاربرد دارد.
//
// این مثال پایه‌ای برای مباحث بعدی مانند:
// - محاسبه مجموع یک ستون
// - پیدا کردن بزرگ‌ترین مقدار در یک ستون
// - کپی کردن یک ستون از ماتریس
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{

    int x[2][3] = {
        {8, 4, 12},
        {10, 6, 9}};

    int j;

    for (j = 0; j < 2; j = j + 1)
    {
        cout << x[j][2] << "\t";
    }

    cout << "\n";

    return 0;
}

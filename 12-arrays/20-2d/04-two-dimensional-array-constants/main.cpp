// -----------------------------------------------------------------------------
// استفاده از ثابت ها برای تعیین اندازه هر بعد
// این برنامه یک مثال آموزشی برای کار با «آرایه‌های دوبعدی» در ++C است.
// نسخه حاضر از ثابت‌ها (const) برای تعیین تعداد سطرها و ستون‌ها استفاده می‌کند.
//
// هدف آموزشی مثال:
// - تعریف آرایه دوبعدی با استفاده از ثابت‌ها (NUM_ROW و NUM_COL)
// - استفاده از حلقه‌های تو در تو برای دریافت داده‌ها
// - نمایش آرایه در قالب جدول
// - تفکیک بهتر منطق برنامه و افزایش خوانایی
//
// شرح عملکرد برنامه:
//
// 1. دو ثابت تعریف شده‌اند:
//      NUM_ROW = 2   → تعداد سطرها
//      NUM_COL = 3   → تعداد ستون‌ها
//
// 2. آرایه دوبعدی x با استفاده از این ثابت‌ها ساخته می‌شود:
//      int x[NUM_ROW][NUM_COL];
//
// 3. با دو حلقه for تو در تو، برنامه از کاربر می‌خواهد مقدار هر خانه آرایه
//    را وارد کند. موقعیت هر خانه نیز به صورت (سطر، ستون) نمایش داده می‌شود.
//    مثال: 1,1 یعنی سطر اول، ستون اول.
//
// 4. در بخش نمایش خروجی:
//    - دوباره از دو حلقه تو در تو استفاده شده است.
//    - هر مقدار همراه با '\t' چاپ می‌شود تا خروجی به صورت مرتب و جدولی باشد.
//
// نکات آموزشی:
// - استفاده از ثابت‌ها باعث می‌شود در صورت تغییر ابعاد آرایه، تنها
//   مقدار ثابت‌ها را عوض کنیم و نیازی به تغییر حلقه‌ها نباشد.
// - اندیس آرایه از صفر آغاز می‌شود بنابراین x[0][0] اولین خانه است.
//
// این مثال پایه‌ای برای تمرین‌های پیشرفته‌تر مانند کار با ماتریس‌ها،
// جمع سطر/ستون‌ها، و محاسبات جدولی می‌باشد.
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    const int NUM_ROW = 2;
    const int NUM_COL = 3;

    int x[NUM_ROW][NUM_COL];
    int j, i;

    for (j = 0; j < NUM_ROW; j = j + 1)
    {
        for (i = 0; i < NUM_COL; i = i + 1)
        {
            cout << "Please enter (" << j + 1 << "," << i + 1 << "): ";
            cin >> x[j][i];
        }
    }

    for (j = 0; j < NUM_ROW; j = j + 1)
    {
        for (i = 0; i < NUM_COL; i = i + 1)
        {
            cout << x[j][i] << "\t";
        }

        cout << "\n";
    }

    return 0;
}

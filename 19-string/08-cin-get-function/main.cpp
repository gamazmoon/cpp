// -----------------------------------------------------------------------------
// مثال: دریافت رشته‌های چندکلمه‌ای (جملات) از کاربر
// این برنامه تفاوت بین cin و تابع cin.get را برای خواندن متن آموزش می‌دهد.
//
// هدف آموزشی:
// - یادگیری نحوه دریافت نام و نام خانوادگی (یا جملات دارای Space).
// - درک محدودیت cin در مواجهه با کاراکترهای White-space (فاصله، اینتر، تب).
//
// شرح عملکرد برنامه:
// 1. ابتدا با cin سعی می‌کنیم یک نام کامل بگیریم (که معمولاً فقط کلمه اول ذخیره می‌شود).
// 2. سپس با استفاده از تابع cin.get، یاد می‌گیریم چطور کل خط را تا زدن کلید Enter بخوانیم.
//
// پارامترهای cin.get(اسم_آرایه, حداکثر_طول):
// - اسم_آرایه: متغیری که متن در آن ذخیره شود.
// - حداکثر_طول: برای جلوگیری از سرریز شدن حافظه (مثلاً 50 کاراکتر).
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    char fullName[50];

    cout << "Enter your full name: ";

    // استفاده از cin.get برای خواندن کامل سطر (شامل فاصله‌ها)
    // این تابع تا 50 کاراکتر را می‌خواند یا تا زمانی که کاربر Enter بزند.
    cin.get(fullName, 50);

    cout << "Hello, " << fullName << "!" << "\n";
    cout << "Welcome to Gamazmoon programming course." << "\n";

    return 0;
}

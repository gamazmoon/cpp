// -----------------------------------------------------------------------------
// مثال: جستجو و پردازش در متن (شمارش تکرار یک حرف)
// این برنامه یک جمله را گرفته و تعداد دفعات تکرار حرف 'a' را در آن می‌شمارد.
//
// هدف آموزشی:
// - تمرین پیمایش رشته‌ها با حلقه.
// - استفاده از دستورات شرطی برای تحلیل محتوای یک متن.
//
// سناریو:
// کاربر یک جمله وارد می‌کند و برنامه بررسی می‌کند که چند بار حرف 'a' در آن به کار رفته است.
// این تکنیک پایه و اساس الگوریتم‌های جستجو در متن است.
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    char text[100];
    int count = 0;

    cout << "Enter a sentence: ";
    cin.get(text, 100);

    // پیمایش تک‌تک کاراکترها تا رسیدن به پایان رشته (\0)
    for (int i = 0; text[i] != '\0'; i++)
    {
        // بررسی کوچک یا بزرگ بودن حرف 'a'
        if (text[i] == 'a' || text[i] == 'A')
        {
            count++;
        }
    }

    cout << "The letter 'a' appeared " << count << " times in your text." << endl;

    return 0;
}

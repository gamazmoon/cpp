// -----------------------------------------------------------------------------
// معرفی آرایه کاراکتری و مفهوم انتهای رشته (Null Terminator)
// این برنامه نحوه تعریف و نمایش یک رشته (String) را به روش سنتی C آموزش می‌دهد.
//
// هدف آموزشی:
// - درک اینکه رشته در واقع یک آرایه از نوع char است.
// - آشنایی با کاراکتر صفر یا '\0' که پایان رشته را به کامپایلر اعلام می‌کند.
//
// شرح عملکرد برنامه:
// 1. یک آرایه از کاراکترها به نام name تعریف شده که عبارت "GamAzmoon" را در خود دارد.
// 2. کامپایلر به صورت خودکار یک خانه اضافه در انتهای آرایه برای '\0' در نظر می‌گیرد.
// 3. با استفاده از حلقه for، تک‌تک حروف تا قبل از رسیدن به کاراکتر پایانی چاپ می‌شوند.
//
// نکات مهم:
// - تفاوت کوتیشن تک ('A') برای کاراکتر و کوتیشن دوبل ("A") برای رشته.
// - اگر کاراکتر '\0' نباشد، دستور cout نمی‌داند کجا باید چاپ کردن را متوقف کند.
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    // تعریف رشته به صورت آرایه‌ای از کاراکترها
    char name[] = "GamAzmoon";

    // نمایش مستقیم رشته (ساده‌ترین روش)
    cout << "Full String: " << name << "\n";

    // نمایش رشته با پیمایش حلقه (برای درک ساختار آرایه‌ای)
    cout << "Character by character: ";
    for (int i = 0; name[i] != '\0'; i++)
    {
        cout << name[i] << " ";
    }

    cout << "\n";
    return 0;
}

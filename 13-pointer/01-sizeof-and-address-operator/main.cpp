// -----------------------------------------------------------------------------
// مثال استفاده از sizeof و عملگر آدرس (&) در ++C
// این برنامه یک مثال آموزشی درباره:
//
// - عملگر sizeof
// - آدرس متغیرها در حافظه
// - عملگر & (Address-of Operator)
//
// در زبان ++C است.
//
// هدف آموزشی مثال:
// - آشنایی با اندازه‌ی متغیرها در حافظه
// - درک اینکه هر متغیر در حافظه یک آدرس دارد
// - مشاهده تفاوت بین «مقدار متغیر» و «آدرس متغیر»
//
// -----------------------------------------------------------------------------
//
// شرح عملکرد برنامه:
//
// 1. دو متغیر تعریف شده‌اند:
//
//        int x = 10;
//        int y;
//
// 2. دستور:
//
//        cout << sizeof x;
//
//    اندازه‌ی متغیر x را بر حسب بایت نمایش می‌دهد.
//    معمولاً اندازه int برابر 4 بایت است (بسته به سیستم ممکن است متفاوت باشد).
//
// 3. دستور:
//
//        cout << x;
//
//    مقدار متغیر x را چاپ می‌کند (که برابر 10 است).
//
// 4. دستور:
//
//        cout << &x;
//
//    آدرس حافظه‌ی متغیر x را چاپ می‌کند.
//    علامت & به معنی «آدرسِ» متغیر است.
//
// 5. دستور:
//
//        cout << &y;
//
//    آدرس متغیر y را نیز نمایش می‌دهد.
//    توجه کنید که y مقداردهی نشده است، اما همچنان در حافظه آدرس دارد.
//
// -----------------------------------------------------------------------------
//
// نکات آموزشی مهم:
//
// ✅ sizeof اندازه‌ی نوع داده یا متغیر را بر حسب بایت برمی‌گرداند.
// ✅ هر متغیر در حافظه یک آدرس منحصر‌به‌فرد دارد.
// ✅ عملگر & برای گرفتن آدرس متغیر استفاده می‌شود.
// ✅ مقدار متغیر با آدرس آن متفاوت است.
//
// این مثال پایه‌ای برای مباحث پیشرفته‌تر مانند:
// - اشاره‌گرها (Pointers)
// - مدیریت حافظه
// - ارسال پارامتر با آدرس
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    int x = 10;
    int y;

    // cout << sizeof(int);
    cout << sizeof x;
    cout << endl;

    cout << x;
    cout << endl;

    cout << &x;
    cout << endl;

    cout << &y;
    cout << endl;

    return 0;
}

// -----------------------------------------------------------------------------
// مثال: استفاده از پارامترهای پیش‌فرض (Default Arguments)
//
// هدف آموزشی:
// - آشنایی با پارامترهای پیش‌فرض در توابع
// - مشاهده حالت‌های مختلف فراخوانی تابع
//
// -----------------------------------------------------------------------------
// در این برنامه تابعی به نام line تعریف کرده‌ایم که یک خط از
// یک کاراکتر را چند بار چاپ می‌کند.
//
// این تابع دو پارامتر دارد:
//
// ch      → کاراکتری که باید چاپ شود
// length  → تعداد دفعات چاپ کاراکتر
//
// برای این دو پارامتر مقدار پیش‌فرض تعیین کرده‌ایم:
//
//      char ch = '*'
//      int length = 20
//
// اگر هنگام فراخوانی تابع مقداری ارسال نشود،
// این مقادیر پیش‌فرض استفاده خواهند شد.
//
// -----------------------------------------------------------------------------
// حالت‌های مختلف فراخوانی:
//
// 1️⃣ استفاده از هر دو مقدار پیش‌فرض
//
//      line();
//
// خروجی: 20 ستاره
//
// 2️⃣ تغییر فقط کاراکتر
//
//      line('#');
//
// خروجی: 20 عدد #
//
// 3️⃣ تغییر هر دو مقدار
//
//      line('-', 10);
//
// خروجی: 10 عدد -
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

void line(char ch = '*', int length = 20)
{
    for (int i = 1; i <= length; i = i + 1)
    {
        cout << ch;
    }
    cout << "\n";

    return;
}

int main()
{
    // استفاده از مقدارهای پیش‌فرض
    line();

    // تغییر فقط کاراکتر
    line('#');

    // تغییر کاراکتر و طول
    line('-', 10);

    return 0;
}

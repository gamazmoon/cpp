// -----------------------------------------------------------------------------
// مثال دوم: پارامتر پیش‌فرض همراه با Prototype
//
// هدف آموزشی:
// - آشنایی با Prototype (اعلان تابع)
// - جدا کردن اعلان تابع از تعریف تابع
// - مشاهده اینکه پارامتر پیش‌فرض در Prototype نوشته می‌شود
//
// -----------------------------------------------------------------------------
// در برنامه‌های بزرگ معمولاً تعریف تابع در پایین فایل
// یا حتی در فایل دیگری قرار می‌گیرد.
//
// برای اینکه کامپایلر قبل از رسیدن به تعریف تابع بداند
// چنین تابعی وجود دارد، از "Prototype" استفاده می‌کنیم.
//
// Prototype فقط اعلان تابع است و بدنه ندارد.
//
// مثال:
//
//      int power(int x, int y = 2);
//
// این خط به کامپایلر می‌گوید:
//
// تابعی به نام power وجود دارد که:
//
// - دو پارامتر از نوع int می‌گیرد
// - مقدار int برمی‌گرداند
// - پارامتر دوم مقدار پیش‌فرض 2 دارد
//
// -----------------------------------------------------------------------------
// در این مثال:
//
//      power(5)
//
// چون مقدار دوم داده نشده است، مقدار پیش‌فرض 2 استفاده می‌شود.
//
//      power(5,3)
//
// در این حالت مقدار پیش‌فرض استفاده نمی‌شود.
//
// -----------------------------------------------------------------------------
// نکته مهم:
//
// وقتی پارامتر پیش‌فرض در Prototype نوشته می‌شود،
// نباید در تعریف تابع دوباره نوشته شود.
//
// -----------------------------------------------------------------------------

#include <iostream>
#include <math.h>

using namespace std;

int power(int x, int y = 2);

int main()
{
    cout << power(5) << "\n";
    cout << power(5, 3) << "\n";

    return 0;
}

int power(int x, int y)
{
    return pow(x, y);
}

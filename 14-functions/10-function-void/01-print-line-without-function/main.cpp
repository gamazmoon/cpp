// -----------------------------------------------------------------------------
// مثال اول: تعریف مسئله (بدون استفاده از تابع)
//
// هدف آموزشی:
// - نشان دادن یک مسئله ساده در برنامه
// - آماده‌سازی ذهن دانشجو برای استفاده از تابع
//
// -----------------------------------------------------------------------------
// در این برنامه می‌خواهیم یک خط شامل چند ستاره چاپ کنیم.
//
// در حال حاضر این کار را مستقیماً داخل تابع main انجام داده‌ایم:
//
//      cout << "*****";
//
// در برنامه‌های کوچک این روش مشکلی ایجاد نمی‌کند.
// اما اگر بخواهیم چند بار این خط را چاپ کنیم، مجبور می‌شویم
// این دستور را چندین بار تکرار کنیم.
//
// تکرار کد باعث می‌شود برنامه:
//
// - طولانی‌تر شود
// - خوانایی کمتری داشته باشد
// - نگهداری آن سخت‌تر شود
//
// در مثال بعدی همین مسئله را با استفاده از "تابع" حل می‌کنیم
// تا کد ما تمیزتر و قابل استفاده مجدد شود.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    cout << "*****" << "\n";

    return 0;
}

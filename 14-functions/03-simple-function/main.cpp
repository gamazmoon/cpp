// -----------------------------------------------------------------------------
// مثال تعریف اولین تابع در ++C
//
// هدف آموزشی مثال:
// - آشنایی با نحوه تعریف یک تابع توسط برنامه‌نویس
// - آشنایی با مقدار بازگشتی (return value)
// - نحوه صدا زدن تابع در main
//
// -----------------------------------------------------------------------------
// تعریف تابع
//
// در زبان ++C برنامه‌نویس می‌تواند تابع‌های مخصوص خود را تعریف کند.
//
// شکل کلی تعریف تابع:
//
//      return_type function_name()
//      {
//          instructions
//          return value;
//      }
//
// در این مثال:
//
//      int f()
//
// یعنی تابعی به نام f تعریف شده که خروجی آن عدد صحیح (int) است.
//
// -----------------------------------------------------------------------------
// دستور return
//
// دستور return مقدار خروجی تابع را مشخص می‌کند.
//
// در این مثال:
//
//      return 10;
//
// یعنی این تابع همیشه مقدار 10 را برمی‌گرداند.
//
// -----------------------------------------------------------------------------
// فراخوانی تابع
//
// برای اجرای تابع از نام آن استفاده می‌کنیم:
//
//      f();
//
// اگر تابع خروجی داشته باشد می‌توان آن را در یک متغیر ذخیره کرد:
//
//      int a = f();
//
// -----------------------------------------------------------------------------
// نکته آموزشی:
//
// - هر تابع می‌تواند یک مقدار خروجی داشته باشد.
// - خروجی تابع می‌تواند داخل متغیر ذخیره شود.
// - main نیز خود یک تابع است.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int f()
{
    return 10;
}

int main()
{
    int a;

    a = f();

    cout << a;

    return 0;
}

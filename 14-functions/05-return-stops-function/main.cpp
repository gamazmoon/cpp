// -----------------------------------------------------------------------------
// مثال بررسی رفتار دستور return در تابع
//
// هدف آموزشی مثال:
// - درک نحوه پایان اجرای تابع
// - آشنایی با این نکته که بعد از return کدی اجرا نمی‌شود
//
// -----------------------------------------------------------------------------
// دستور return
//
// زمانی که برنامه به دستور return می‌رسد:
//
// 1) مقدار مشخص شده بازگردانده می‌شود
// 2) اجرای تابع بلافاصله پایان می‌یابد
//
// -----------------------------------------------------------------------------
// مثال:
//
// در تابع زیر چند دستور return نوشته شده است:
//
//      return 10;
//      return 20;
//      return 30;
//
// اما فقط اولین return اجرا می‌شود.
//
// بنابراین خروجی تابع همیشه:
//
//      10
//
// خواهد بود.
//
// دستورات بعد از return هرگز اجرا نمی‌شوند.
//
// -----------------------------------------------------------------------------
// نکته آموزشی:
//
// - وجود چند return در یک تابع ممکن است.
// - اما فقط اولین return که اجرا شود باعث پایان تابع می‌شود.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int f()
{
    return 10;
    return 20;
    return 30;
}

int main()
{
    int a = f();
    cout << a;

    return 0;
}

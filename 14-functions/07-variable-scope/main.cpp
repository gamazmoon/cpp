// -----------------------------------------------------------------------------
// مثال درک Scope (محدوده دید) و تشابه اسمی (Shadowing) در ++C
//
// هدف آموزشی مثال:
// - درک اینکه متغیرهای داخل هر تابع مستقل از هم هستند
// - متغیرهای هم‌نام در توابع مختلف هیچ ارتباطی با هم ندارند
// - فهم این موضوع که هر تابع "فضای محلی" خودش را دارد (Local Scope)
//
// -----------------------------------------------------------------------------
// مفهوم Scope:
//
// وقتی متغیری داخل یک تابع تعریف می‌شود:
//
//      int x = 10;
//
// این متغیر فقط در همان تابع قابل استفاده است.
//
// اگر در تابع دیگری هم متغیر x تعریف کنیم:
//
//      int x = 20;
//
// این دو x کاملاً مستقل از هم هستند.
//
// -----------------------------------------------------------------------------
// تشابه اسمی (Shadowing):
//
// اگر داخل یک تابع متغیری تعریف شود که نامش با متغیر بیرون از آن بلوک یکسان باشد،
// متغیر داخلی، متغیر بیرونی را "پوشش" می‌دهد.
//
// در این مثال global نداریم، اما دو متغیر هم‌نام داریم:
//
// - x در تابع f
// - x در تابع main
//
// این‌ها دو متغیر متفاوت‌اند.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int f()
{
    int x = 10; // این x فقط برای تابع f است
    return x;
}

int main()
{
    int x = 50; // این x ربطی به x داخل f ندارد

    cout << f() << "\n";
    cout << x << "\n";

    return 0;
}

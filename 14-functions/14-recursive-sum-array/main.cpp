// -----------------------------------------------------------------------------
// مثال: محاسبه مجموع عناصر آرایه با استفاده از تابع بازگشتی
//
// هدف آموزشی:
// - آشنایی با مفهوم بازگشت (Recursion)
// - تشخیص حالت پایه (Base Case) در تابع بازگشتی
// - حل یک مسئله با کوچک‌تر کردن تدریجی ورودی
//
// -----------------------------------------------------------------------------
// در این برنامه می‌خواهیم مجموع عناصر یک آرایه را حساب کنیم.
//
// آرایه‌ی ما به صورت زیر است:
//
//      {5, 8, 4, 6}
//
// اگر بخواهیم مجموع این آرایه را به صورت عادی حساب کنیم، داریم:
//
//      5 + 8 + 4 + 6 = 23
//
// اما هدف این مثال فقط به‌دست آوردن جواب نیست.
// هدف اصلی این است که یاد بگیریم چگونه همین مسئله را
// با استفاده از "تابع بازگشتی" حل کنیم.
//
// ایده‌ی بازگشتی این مثال:
//
// مجموع n عنصر اول آرایه برابر است با:
//
//      مجموع n-1 عنصر اول
//      +
//      عنصر آخر
//
// یعنی:
//
//      sum(a, n) = sum(a, n - 1) + a[n - 1]
//
// اما هر تابع بازگشتی باید یک "حالت توقف" داشته باشد.
// در اینجا اگر تعداد عناصر برابر صفر باشد، یعنی آرایه خالی است
// و مجموع آن برابر صفر خواهد بود.
//
//      sum(a, 0) = 0
//
// بنابراین ساختار کلی تابع بازگشتی ما این‌گونه است:
//
// 1) اگر آرایه خالی بود => جواب صفر
// 2) در غیر این صورت => مسئله را کوچک‌تر کن و دوباره تابع را صدا بزن
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

// تابع بازگشتی برای محاسبه مجموع عناصر آرایه
int sum(int a[], int n)
{
    // -------------------------------------------------------------------------
    // حالت پایه (Base Case)
    //
    // اگر تعداد عناصر صفر باشد، یعنی آرایه خالی است
    // و مجموع عناصر آن برابر صفر است.
    // -------------------------------------------------------------------------
    if (n == 0)
    {
        return 0;
    }

    // -------------------------------------------------------------------------
    // فراخوانی بازگشتی
    //
    // مجموع n عنصر اول برابر است با:
    // مجموع n-1 عنصر اول + عنصر آخر
    //
    // a[n - 1] یعنی آخرین عنصر در بخش فعلی آرایه
    // -------------------------------------------------------------------------
    return sum(a, n - 1) + a[n - 1];
}

int main()
{
    int x[] = {5, 8, 4, 6};

    int result = sum(x, 4);

    cout << "Sum = " << result << "\n";

    return 0;
}

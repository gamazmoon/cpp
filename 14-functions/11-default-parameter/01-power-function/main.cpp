// -----------------------------------------------------------------------------
// مثال اول: پارامتر پیش‌فرض (Default Argument)
//
// هدف آموزشی:
// - آشنایی با مفهوم پارامتر پیش‌فرض در توابع
// - درک اینکه چگونه می‌توان یک مقدار اولیه برای پارامتر تعیین کرد
// - مشاهده اینکه هنگام فراخوانی تابع می‌توان آن مقدار را تغییر داد
//
// -----------------------------------------------------------------------------
// پارامتر پیش‌فرض چیست؟
//
// در C++ می‌توان برای پارامترهای تابع یک مقدار پیش‌فرض تعیین کرد.
//
// اگر هنگام فراخوانی تابع مقداری برای آن پارامتر ارسال نشود،
// همان مقدار پیش‌فرض استفاده می‌شود.
//
// مثال:
//
//      int power(int x, int y = 2)
//
// در این تابع:
//
// x  → پایه توان
// y  → توان
//
// اگر مقدار y داده نشود، مقدار پیش‌فرض آن یعنی 2 استفاده می‌شود.
//
// -----------------------------------------------------------------------------
// مثال:
//
//      power(5)
//
// در این حالت مقدار y برابر 2 در نظر گرفته می‌شود:
//
//      5^2 = 25
//
// اما اگر مقدار دوم داده شود:
//
//      power(5,3)
//
// در این صورت مقدار پیش‌فرض استفاده نمی‌شود و توان برابر 3 خواهد بود:
//
//      5^3 = 125
//
// -----------------------------------------------------------------------------

#include <iostream>
#include <math.h>

using namespace std;

int power(int x, int y = 2)
{
    return pow(x, y);
}

int main()
{
    cout << power(5) << "\n";
    cout << power(5, 3) << "\n";

    return 0;
}

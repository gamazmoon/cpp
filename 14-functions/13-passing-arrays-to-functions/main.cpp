#include <iostream>
using namespace std;

// تابع فقط با نام آرایه کار می‌کند (نیازی به علامت & نیست)
void readArray(int arr[], int size)
{
    for (int i = 0; i < size; i = i + 1)
    {
        cin >> arr[i];
    }
}

void printArray(int arr[], int size)
{
    for (int i = 0; i < size; i = i + 1)
    {
        cout << arr[i] << " ";
    }
}

int main()
{
    int data[5];
    readArray(data, 5);
    printArray(data, 5);
    return 0;
}

// -----------------------------------------------------------------------------
// مثال تابع با چند پارامتر
//
// هدف آموزشی مثال:
// - آشنایی با ارسال چند ورودی به تابع
// - انجام عملیات روی چند مقدار
//
// -----------------------------------------------------------------------------
// چند پارامتر در تابع
//
// یک تابع می‌تواند چند پارامتر داشته باشد.
//
// شکل کلی:
//
//      return_type function_name(type p1, type p2)
//
// مثال:
//
//      int g(int a, int b)
//
// -----------------------------------------------------------------------------
// عملکرد تابع
//
// در این مثال تابع دو عدد را دریافت می‌کند:
//
//      a
//      b
//
// و مجموع آن‌ها را برمی‌گرداند:
//
//      a + b
//
// -----------------------------------------------------------------------------
// فراخوانی تابع
//
// برای استفاده از تابع:
//
//      g(3, 4)
//
// در این حالت:
//
//      a = 3
//      b = 4
//
// خروجی:
//
//      7
//
// -----------------------------------------------------------------------------
// نکته آموزشی:
//
// - پارامترها با کاما از هم جدا می‌شوند.
// - ترتیب ارسال پارامترها مهم است.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int g(int a, int b)
{
    return a + b;
}

int main()
{
    int a = g(3, 4);
    cout << a;

    return 0;
}

// -----------------------------------------------------------------------------
// مثال تابع با ورودی (پارامتر)
//
// هدف آموزشی مثال:
// - آشنایی با پارامترهای تابع
// - ارسال داده به تابع
// - استفاده از ورودی در محاسبات
//
// -----------------------------------------------------------------------------
// پارامتر تابع
//
// تابع می‌تواند از بیرون برنامه داده دریافت کند.
//
// شکل کلی:
//
//      return_type function_name(parameter)
//
// مثال:
//
//      int square(int x)
//
// در اینجا:
//
// - square نام تابع است
// - x پارامتر تابع است
//
// -----------------------------------------------------------------------------
// عملکرد تابع square
//
// این تابع مربع یک عدد را محاسبه می‌کند.
//
// یعنی:
//
//      x * x
//
// مثال:
//
//      square(3) -> 9
//
// -----------------------------------------------------------------------------
// ارسال مقدار به تابع
//
// هنگام فراخوانی تابع مقدار ورودی ارسال می‌شود:
//
//      square(3)
//
// در این حالت:
//
//      x = 3
//
// -----------------------------------------------------------------------------
// نکته آموزشی:
//
// - پارامترها امکان ارسال داده به تابع را فراهم می‌کنند.
// - توابع می‌توانند برای انجام محاسبات مختلف استفاده شوند.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int square(int x)
{
    return x * x;
}

int main()
{
    int a = square(3);
    cout << a;

    return 0;
}

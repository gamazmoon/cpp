// -----------------------------------------------------------------------------
// مثال آشنایی با مفهوم تابع در ++C (با استفاده از تابع abs)
// این برنامه برای آشنایی با مفهوم تابع (Function) در زبان ++C نوشته شده است.
// در این مثال از تابع آماده‌ی abs به عنوان نمونه استفاده شده است.
//
// هدف آموزشی مثال:
// - آشنایی با مفهوم تابع در برنامه‌نویسی.
// - استفاده از توابع آماده‌ی کتابخانه‌ای.
// - اعمال یک تابع روی عناصر آرایه.
// - استفاده از حلقه برای پردازش داده‌ها.
//
// -----------------------------------------------------------------------------
// مفهوم تابع:
//
// تابع (Function) قطعه‌ای از کد است که یک کار مشخص انجام می‌دهد.
// ما می‌توانیم با ارسال یک مقدار به تابع، نتیجه‌ای از آن دریافت کنیم.
//
// به طور کلی:
//
//        نتیجه = تابع(ورودی)
//
// مثال:
//
//        abs(-16)
//
// در اینجا:
// - abs نام تابع است
// - -16 ورودی تابع است
// - 16 خروجی تابع است
//
// -----------------------------------------------------------------------------
// استفاده از تابع abs:
//
//        cout << abs(-16);
//
// تابع abs قدر مطلق عدد را برمی‌گرداند.
//
// بنابراین:
//
//        abs(-16)  -> 16
//        abs(16)   -> 16
//
// -----------------------------------------------------------------------------
// تعریف آرایه:
//
//        int x[5] = {45, -24, -17, 12, 36};
//
// این آرایه شامل چند عدد مثبت و منفی است.
//
// -----------------------------------------------------------------------------
// تعریف آرایه خروجی:
//
//        int y[5];
//
// در این آرایه نتیجه‌ی اجرای تابع ذخیره می‌شود.
//
// -----------------------------------------------------------------------------
// استفاده از تابع در حلقه:
//
//        y[i] = abs(x[i]);
//
// در هر تکرار حلقه:
//
// 1. مقدار x[i] به تابع abs داده می‌شود.
// 2. تابع قدر مطلق آن را محاسبه می‌کند.
// 3. نتیجه در y[i] ذخیره می‌شود.
//
// -----------------------------------------------------------------------------
// مزیت استفاده از تابع:
//
// به جای نوشتن چندین خط کد برای محاسبه‌ی قدر مطلق،
// می‌توان از یک تابع آماده استفاده کرد.
//
// این کار باعث می‌شود:
//
// - کد کوتاه‌تر شود
// - خوانایی برنامه بهتر شود
// - احتمال خطا کمتر شود
//
// -----------------------------------------------------------------------------
// نکات آموزشی:
//
// - تابع‌ها یکی از مهم‌ترین مفاهیم برنامه‌نویسی هستند.
// - بسیاری از عملیات‌های متداول به صورت تابع در کتابخانه‌ها وجود دارند.
// - می‌توانیم علاوه بر استفاده از توابع آماده، خودمان نیز تابع بنویسیم.
//
// در مباحث بعدی یاد خواهیم گرفت:
// - چگونه تابع تعریف کنیم
// - چگونه پارامتر به تابع بدهیم
// - چگونه مقدار از تابع دریافت کنیم
// -----------------------------------------------------------------------------

#include <iostream>
#include <math.h>

using namespace std;

int main()
{
    cout << abs(-16) << "\t";
    cout << abs(16) << "\t";

    int x[5] = {45, -24, -17, 12, 36};
    int y[5];

    for (int i = 0; i < 5; i = i + 1)
    {
        //---- قدر مطلق x[i]
        int ab = x[i];
        if (x[i] < 0)
        {
            ab = -x[i];
        }
        //--------------

        y[i] = ab;
    }

    for (int i = 0; i < 5; i = i + 1)
    {
        y[i] = abs(x[i]);
    }

    return 0;
}

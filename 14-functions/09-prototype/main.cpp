// -----------------------------------------------------------------------------
// مثال جامع Prototype، Declaration و Definition در ++C
//
// هدف آموزشی:
// - درک مفاهیم کلیدی: Declaration (اعلان)، Prototype (نمونه‌سازی) و Definition (تعریف)
// - یادگیری تفاوت ظریف بین اعلان و تعریف تابع
//
// -----------------------------------------------------------------------------
// ۱. اعلان تابع (Declaration / Prototype):
//
// در ++C، برنامه از بالا به پایین توسط کامپایلر خوانده می‌شود.
// برای اینکه تابع در `main` شناخته شود، قبل از فراخوانی باید آن را به کامپایلر "معرفی" کنیم.
//
// - Prototype یا "اعلان تابع" (Declaration) به کامپایلر می‌گوید:
//   "تابعی با این نام و این ورودی/خروجی وجود دارد، در ادامه تعریفش را می‌بینی."
//
// - شکل کلی: return_type function_name(parameter_types);
//
// -----------------------------------------------------------------------------
// ۲. تعریف تابع (Definition):
//
// - در "تعریف تابع" (Definition)، بدنه اصلی تابع شامل دستوراتی که اجرا می‌شوند، نوشته می‌شود.
// - یک تابع را می‌توان یک بار تعریف کرد، اما می‌توان چندین بار آن را در جاهای مختلف اعلام کرد.
//
// -----------------------------------------------------------------------------
// نکته درباره Prototype و Signature:
//
// - Signature (امضا): ویژگی‌های هویتی تابع (نام + لیست پارامترها).
// - Prototype: همان خطِ اعلان است که Signature تابع را به همراه نوع بازگشتی
//   به کامپایلر گزارش می‌دهد تا اجازه فراخوانی را صادر کند.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

// Declaration
int square(int);
int sumOfSquares(int, int);

int main()
{
    int r = sumOfSquares(3, 4);
    cout << r;

    return 0;
}

// Definition
int square(int x)
{
    return x * x;
}

// Definition
int sumOfSquares(int a, int b)
{
    int s1 = square(a);
    int s2 = square(b);
    return s1 + s2;
}

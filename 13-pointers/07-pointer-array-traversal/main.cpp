// -----------------------------------------------------------------------------
// مثال پیمایش آرایه با استفاده از آرایه و اشاره‌گر در ++C
// این برنامه چند روش مختلف برای دسترسی به عناصر آرایه را نشان می‌دهد.
//
// هدف آموزشی مثال:
// - درک رابطه‌ی آرایه و اشاره‌گر.
// - پیمایش آرایه با استفاده از حلقه.
// - دسترسی به عناصر آرایه با سه روش مختلف.
// - آشنایی با Pointer Arithmetic در حلقه‌ها.
//
// شرح عملکرد برنامه:
//
// 1. تعریف آرایه:
//
//        int x[3] = {12, 2, 5};
//
//    یک آرایه شامل سه عدد صحیح ایجاد می‌شود.
//
// 2. تعریف اشاره‌گر:
//
//        int *p = x;
//
//    نام آرایه به آدرس اولین عنصر آن تبدیل می‌شود.
//    بنابراین اشاره‌گر p به اولین عنصر آرایه اشاره می‌کند.
//
// -----------------------------------------------------------------------------
// روش اول: دسترسی با استفاده از آرایه
//
//        cout << x[i];
//
//    در این روش عناصر آرایه به شکل معمولی با استفاده از اندیس i
//    خوانده می‌شوند.
//
// -----------------------------------------------------------------------------
// روش دوم: دسترسی با ایندکس روی اشاره‌گر
//
//        cout << p[i];
//
//    اشاره‌گرها نیز می‌توانند مانند آرایه‌ها با [] استفاده شوند.
//    بنابراین:
//
//        p[i]
//
//    معادل:
//
//        x[i]
//
//    است.
//
// -----------------------------------------------------------------------------
// روش سوم: استفاده از Pointer Arithmetic
//
//        cout << *(p + i);
//
//    در این روش:
//
//        p + i
//
//    آدرس عنصر iام را تولید می‌کند.
//
//    سپس:
//
//        *(p + i)
//
//    مقدار موجود در آن آدرس را برمی‌گرداند.
//
//    بنابراین:
//
//        *(p + i)
//
//    معادل:
//
//        p[i]
//        x[i]
//
//    است.
//
// -----------------------------------------------------------------------------
// روش چهارم: حرکت خود اشاره‌گر در حافظه
//
//        p = p + 1
//
//    در این حلقه اشاره‌گر در هر تکرار یک خانه جلوتر می‌رود.
//
//    بنابراین:
//
//        *p
//
//    مقدار عنصر فعلی آرایه را چاپ می‌کند.
//
//    این روش نشان می‌دهد که اشاره‌گر می‌تواند مانند یک نشانگر
//    برای حرکت بین عناصر آرایه استفاده شود.
//
// -----------------------------------------------------------------------------
// معادل‌های مهم:
//
//        x[i]
//        p[i]
//        *(p + i)
//
// همه به یک عنصر از آرایه اشاره می‌کنند.
//
// -----------------------------------------------------------------------------
// نکته مهم:
//
// در حلقه‌ی آخر مقدار اشاره‌گر p تغییر می‌کند.
// بنابراین بعد از پایان حلقه، p دیگر به ابتدای آرایه اشاره نمی‌کند.
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    int x[3] = {12, 2, 5};
    int *p = x;

    for (int i = 0; i < 3; i = i + 1)
    {
        cout << x[i];
    }
    cout << "\n";

    for (int i = 0; i < 3; i = i + 1)
    {
        cout << p[i];
    }
    cout << "\n";

    for (int i = 0; i < 3; i = i + 1)
    {
        cout << *(p + i);
    }
    cout << "\n";

    for (int i = 0; i < 3; i = i + 1, p = p + 1)
    {
        cout << *p;
    }

    return 0;
}

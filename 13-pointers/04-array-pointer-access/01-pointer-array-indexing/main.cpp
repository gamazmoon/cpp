// -----------------------------------------------------------------------------
// مثال دسترسی به عناصر آرایه با ایندکس‌گذاری روی اشاره‌گر در ++C
// این برنامه یک مثال آموزشی برای آشنایی با استفاده از عملگر [] روی
// اشاره‌گرها در زبان ++C است.
//
// هدف آموزشی مثال:
// - درک ارتباط بین آرایه و اشاره‌گر.
// - دسترسی به عناصر آرایه از طریق اشاره‌گر.
// - استفاده از عملگر [] روی اشاره‌گر.
// - تغییر مقدار عناصر آرایه با اشاره‌گر.
//
// شرح عملکرد برنامه:
//
// 1. تعریف آرایه:
//        int x[3] = {12, 2, 5};
//
//    یک آرایه از سه عدد صحیح تعریف می‌شود.
//
// 2. تعریف اشاره‌گر:
//        int *p = x;
//
//    نام آرایه به آدرس اولین عنصر آن تبدیل می‌شود.
//    بنابراین p به اولین عنصر آرایه اشاره می‌کند.
//
// 3. دسترسی به عناصر:
//
//        cout << p[0];
//        cout << p[1];
//        cout << p[2];
//
//    اشاره‌گر p مانند آرایه رفتار می‌کند و می‌توان با [] به عناصر دسترسی داشت.
//
//    عبارت‌های زیر معادل هستند:
//
//        p[0] == x[0]
//        p[1] == x[1]
//        p[2] == x[2]
//
// 4. تغییر مقدار عنصر:
//
//        p[0]++;
//
//    این دستور مقدار اولین عنصر آرایه را یک واحد افزایش می‌دهد.
//
//    چون p به آرایه اشاره می‌کند، تغییر مستقیماً روی آرایه اعمال می‌شود.
//
// نکات آموزشی:
// - اشاره‌گرها می‌توانند مانند آرایه ایندکس‌گذاری شوند.
// - تغییر داده از طریق اشاره‌گر باعث تغییر مقدار اصلی آرایه می‌شود.
// - آرایه و اشاره‌گر ارتباط نزدیکی با یکدیگر دارند.
//
// این مفهوم پایه‌ای برای:
// - پیمایش آرایه‌ها
// - ارسال آرایه به توابع
// - کار با حافظه
// - ساختمان داده‌ها
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    int x[3] = {12, 2, 5};

    int *p = x;

    cout << p[0];
    cout << "\n";

    cout << p[1];
    cout << "\n";

    cout << p[2];
    cout << "\n";

    p[0]++;

    cout << p[0];

    return 0;
}

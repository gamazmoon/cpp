// -----------------------------------------------------------------------------
// مثال نمایش آدرس آرایه و ارتباط آن با اشاره‌گر در ++C
// این برنامه یک مثال آموزشی برای درک نحوه‌ی نمایش آدرس آرایه و ارتباط آن با
// اشاره‌گرها در زبان ++C است.
//
// هدف آموزشی مثال:
// - مشاهده‌ی آدرس حافظه‌ی یک آرایه.
// - درک این نکته که نام آرایه در بسیاری از عبارات به آدرس اولین عنصر آن تبدیل می‌شود.
// - آشنایی با مقداردهی یک اشاره‌گر با استفاده از نام آرایه.
//
// شرح عملکرد برنامه:
//
// 1. تعریف آرایه:
//        int x[3] = {12, 2, 5};
//    در این خط یک آرایه از سه عدد صحیح تعریف و مقداردهی اولیه می‌شود.
//
// 2. چاپ نام آرایه:
//        cout << x;
//    در اینجا نام آرایه (x) در واقع به آدرس اولین عنصر آرایه تبدیل می‌شود.
//    بنابراین این دستور آدرس اولین خانه‌ی حافظه‌ی آرایه را چاپ می‌کند.
//
// 3. چاپ آدرس اولین عنصر آرایه:
//        cout << &(x[0]);
//    این دستور نیز آدرس اولین عنصر آرایه را چاپ می‌کند.
//
//    معمولاً خروجی دو دستور بالا یکسان است، زیرا:
//        x  ==  &(x[0])
//
// 4. مقداردهی اشاره‌گر با نام آرایه:
//        int *p = x;
//    چون نام آرایه معادل آدرس اولین عنصر آن است، می‌توان آن را در یک اشاره‌گر
//    از نوع int ذخیره کرد. در نتیجه اشاره‌گر p به اولین عنصر آرایه اشاره می‌کند.
//
// نکات آموزشی:
// - نام آرایه در بسیاری از عبارات به اشاره‌گر به اولین عنصر آن تبدیل می‌شود.
// - به همین دلیل می‌توان نام آرایه را مستقیماً به یک اشاره‌گر نسبت داد.
// - این ویژگی پایه‌ای برای کار با اشاره‌گرها و پیمایش آرایه‌ها است.
//
// این مفهوم در مباحث پیشرفته‌تر مانند موارد زیر استفاده می‌شود:
// - پیمایش آرایه‌ها با اشاره‌گر
// - محاسبات اشاره‌گری (Pointer Arithmetic)
// - ارسال آرایه‌ها به توابع
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    int x[3] = {12, 2, 5};

    cout << x;
    cout << "\n";
    cout << &(x[0]);

    int *p = x;
    return 0;
}

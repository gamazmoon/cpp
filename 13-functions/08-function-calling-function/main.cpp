// -----------------------------------------------------------------------------
// مثال تابعی که تابع دیگری را فراخوانی می‌کند در ++C
//
// هدف آموزشی مثال:
// - آشنایی با برنامه‌ای که بیش از یک تابع دارد
// - یادگیری نحوه‌ی فراخوانی یک تابع از داخل تابع دیگر
// - مشاهده‌ی استفاده‌ی مجدد از کد
// - آشنایی با طراحی برنامه به صورت ماژولار
//
// -----------------------------------------------------------------------------
// معرفی برنامه
//
// در این برنامه دو تابع تعریف شده است:
//
//      square(x)
//      sumOfSquares(a, b)
//
// تابع square مربع یک عدد را محاسبه می‌کند.
//
// تابع sumOfSquares مجموع مربع‌های دو عدد را به دست می‌آورد.
//
// -----------------------------------------------------------------------------
// تابع square
//
// شکل تابع:
//
//      int square(int x)
//
// این تابع یک عدد را دریافت می‌کند و مربع آن را برمی‌گرداند.
//
// یعنی:
//
//      square(x) = x * x
//
// مثال:
//
//      square(3) -> 9
//      square(4) -> 16
//
// -----------------------------------------------------------------------------
// تابع sumOfSquares
//
// شکل تابع:
//
//      int sumOfSquares(int a, int b)
//
// این تابع دو عدد را دریافت می‌کند.
//
// سپس:
//
// 1) مربع عدد اول را با کمک تابع square حساب می‌کند
// 2) مربع عدد دوم را با کمک تابع square حساب می‌کند
// 3) مجموع این دو مقدار را برمی‌گرداند
//
// در واقع:
//
//      sumOfSquares(a, b) = square(a) + square(b)
//
// -----------------------------------------------------------------------------
// فراخوانی تابع از داخل تابع دیگر
//
// در این قسمت:
//
//      int s1 = square(a);
//      int s2 = square(b);
//
// تابع sumOfSquares از تابع square استفاده می‌کند.
//
// این کار نشان می‌دهد که در ++C:
//
// - یک تابع می‌تواند تابع دیگری را صدا بزند
// - می‌توان بخش‌های تکراری برنامه را در یک تابع جداگانه نوشت
// - با این روش برنامه خواناتر و منظم‌تر می‌شود
//
// -----------------------------------------------------------------------------
// بررسی اجرای مثال
//
// اگر بنویسیم:
//
//      sumOfSquares(3, 4)
//
// ابتدا:
//
//      square(3) -> 9
//
// سپس:
//
//      square(4) -> 16
//
// در نهایت:
//
//      9 + 16 = 25
//
// بنابراین خروجی برنامه:
//
//      25
//
// خواهد بود.
//
// -----------------------------------------------------------------------------
// نکات آموزشی:
//
// - هر تابع بهتر است یک کار مشخص انجام دهد.
// - تابع‌های کوچک را می‌توان در تابع‌های بزرگ‌تر استفاده کرد.
// - این روش باعث جلوگیری از تکرار کد می‌شود.
// - این نوع طراحی، پایه‌ی برنامه‌نویسی ماژولار است.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int square(int x)
{
    return x * x;
}

int sumOfSquares(int a, int b)
{
    int s1 = square(a);
    int s2 = square(b);
    return s1 + s2;
}

int main()
{
    int r = sumOfSquares(3, 4);
    cout << r;

    return 0;
}

// -----------------------------------------------------------------------------
// مثال آشنایی با توابع ریاضی در ++C
// این برنامه چند تابع پرکاربرد ریاضی را در زبان ++C معرفی می‌کند.
//
// هدف آموزشی مثال:
// - آشنایی بیشتر با مفهوم تابع.
// - استفاده از توابع آماده‌ی ریاضی.
// - یادگیری نحوه‌ی ارسال ورودی به تابع.
// - دریافت مقدار خروجی از تابع.
//
// برای استفاده از توابع ریاضی، کتابخانه‌ی:
//
//        <math.h>
//
// یا:
//
//        <cmath>
//
// استفاده می‌شود.
//
// -----------------------------------------------------------------------------
// مفهوم تابع:
//
// تابع قطعه‌ای از کد است که:
// - ورودی دریافت می‌کند
// - عملیاتی انجام می‌دهد
// - نتیجه‌ای برمی‌گرداند
//
// شکل کلی:
//
//        result = function(input);
//
// مثال:
//
//        abs(-16)
//
// در این مثال:
// - abs نام تابع است
// - -16 ورودی تابع است
// - 16 خروجی تابع است
//
// -----------------------------------------------------------------------------
// تابع abs
//
//        abs(-16)
//
// این تابع قدر مطلق عدد را محاسبه می‌کند.
//
// مثال:
//
//        abs(-16) -> 16
//        abs(16)  -> 16
//
// -----------------------------------------------------------------------------
// تابع pow
//
//        pow(2, 3)
//
// این تابع توان را محاسبه می‌کند.
//
// شکل کلی:
//
//        pow(x, y)
//
// یعنی:
//
//        x ^ y
//
// بنابراین:
//
//        pow(2, 3) -> 8
//
// -----------------------------------------------------------------------------
// تابع round
//
//        round(4.6)
//
// عدد را به نزدیک‌ترین عدد صحیح گرد می‌کند.
//
// مثال:
//
//        round(4.6) -> 5
//        round(4.2) -> 4
//
// -----------------------------------------------------------------------------
// تابع floor
//
//        floor(4.6)
//
// عدد را به سمت پایین گرد می‌کند.
//
// مثال:
//
//        floor(4.6) -> 4
//
// -----------------------------------------------------------------------------
// تابع ceil
//
//        ceil(4.6)
//
// عدد را به سمت بالا گرد می‌کند.
//
// مثال:
//
//        ceil(4.6) -> 5
//
// -----------------------------------------------------------------------------
// تابع max
//
//        max(12, 23)
//
// بزرگ‌ترین مقدار بین دو عدد را برمی‌گرداند.
//
// مثال:
//
//        max(12, 23) -> 23
//
// -----------------------------------------------------------------------------
// استفاده از خروجی تابع:
//
//        int t = max(m, 123);
//
// خروجی تابع می‌تواند داخل متغیر ذخیره شود.
//
// -----------------------------------------------------------------------------
// استفاده از عبارت‌ها به عنوان ورودی تابع:
//
//        max(12, a * 12 + 4);
//
// ورودی تابع می‌تواند:
// - عدد
// - متغیر
// - عبارت ریاضی
// - یا حتی خروجی یک تابع دیگر باشد.
//
// -----------------------------------------------------------------------------
// توابع تو در تو (Nested Functions)
//
//        max(12, max(8, 10));
//
// ابتدا:
//
//        max(8, 10)
//
// اجرا می‌شود.
//
// سپس نتیجه به تابع بیرونی داده می‌شود.
//
// -----------------------------------------------------------------------------
// نکات آموزشی:
//
// - توابع باعث کوتاه‌تر و خواناتر شدن کد می‌شوند.
// - بسیاری از عملیات‌های رایج به صورت تابع آماده وجود دارند.
// - خروجی یک تابع می‌تواند ورودی تابع دیگری باشد.
// - توابع ریاضی در برنامه‌های علمی و مهندسی بسیار پرکاربرد هستند.
//
// این مفاهیم پایه‌ای برای یادگیری:
// - تعریف تابع
// - پارامترها
// - مقدار بازگشتی
// - برنامه‌نویسی ماژولار
// هستند.
// -----------------------------------------------------------------------------

#include <iostream>
#include <math.h>

using namespace std;

int main()
{
    int a, b;

    // abs function
    a = abs(-16);
    b = abs(-16) + 4;
    cout << abs(-16) << "\t";

    // power function x^y
    a = pow(2, 3);
    cout << pow(2, 3) << "\t";

    // round
    cout << round(4.6) << "\t";
    cout << floor(4.6) << "\t";
    cout << ceil(4.6) << "\t";

    cout << max(12, 23);

    int m = 12;
    int t = max(m, 123);

    max(12, a * 12 + 4);

    max(12, max(8, 10));

    return 0;
}

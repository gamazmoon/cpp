// -----------------------------------------------------------------------------
// مثال دوم: حل مسئله با استفاده از تابع void
//
// هدف آموزشی:
// - آشنایی با توابعی که مقدار برنمی‌گردانند
// - معرفی نوع void
// - نشان دادن مزیت استفاده از تابع برای جلوگیری از تکرار کد
//
// -----------------------------------------------------------------------------
// void چیست؟
//
// در ++C هر تابع معمولاً یک مقدار برمی‌گرداند.
// مثلاً:
//
//      int f()
//      {
//          return 10;
//      }
//
// در اینجا تابع یک مقدار از نوع int برمی‌گرداند.
//
// اما گاهی تابع فقط کاری انجام می‌دهد و نیازی به برگرداندن
// مقدار ندارد.
//
// در این حالت از نوع void استفاده می‌کنیم.
//
// شکل کلی:
//
//      void function_name(parameters)
//
// یعنی:
//
// این تابع مقداری برنمی‌گرداند.
//
// -----------------------------------------------------------------------------
// در این مثال تابعی به نام line تعریف کرده‌ایم که یک خط ستاره چاپ می‌کند:
//
//      void line()
//      {
//          cout << "*****";
//      }
//
// حالا هر جا در برنامه به این خط نیاز داشته باشیم
// فقط کافی است تابع line را صدا بزنیم.
//
// این کار باعث می‌شود:
//
// - کد تکراری حذف شود
// - برنامه خواناتر شود
// - تغییرات آینده ساده‌تر انجام شود
//
// -----------------------------------------------------------------------------
// نکته:
//
// در تابع void می‌توان از دستور return استفاده کرد:
//
//      return;
//
// اما در این حالت return مقداری برنمی‌گرداند و فقط
// باعث پایان اجرای تابع می‌شود.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

void line()
{
    cout << "*****" << "\n";

    return;
}

int main()
{
    line();

    return 0;
}

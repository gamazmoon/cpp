// -----------------------------------------------------------------------------
// مثال ۲: نمایش اطلاعات یک کالا با استفاده از Struct
//
// هدف آموزشی:
// - معرفی Struct به عنوان ابزاری برای گروه‌بندی داده‌های مرتبط
// - ساخت یک "مدل داده" برای کالا (Product)
// - یادگیری دسترسی به اعضای Struct با عملگر نقطه (.)
//
// -----------------------------------------------------------------------------
// در مثال قبل، اطلاعات کالا را با چند متغیر جدا نگه داشتیم.
// حالا با Struct، همه ویژگی‌های کالا را داخل یک نوع داده‌ی واحد قرار می‌دهیم.
//
// مزیت Struct چیست؟
// 1) همه اطلاعات یک کالا در یک متغیر (مثلاً p) جمع می‌شود.
// 2) مدیریت چند کالا راحت‌تر می‌شود (آرایه‌ای از Product).
// 3) ارسال/دریافت کالا در توابع ساده‌تر می‌شود (یک پارامتر به جای چند پارامتر).
// 4) کد خواناتر و قابل نگهداری‌تر می‌شود.
//
// نکته مهم:
// - Struct خودش فقط "قالب" است.
// - وقتی از آن متغیر می‌سازیم (مثل Product p;) یعنی یک نمونه (Instance) ساخته‌ایم.
// -----------------------------------------------------------------------------

#include <iostream>
#include <string>
using namespace std;

// تعریف ساختار کالا: قالبی برای نگهداری اطلاعات یک Product
struct Product
{
    int id;
    string name;
    int stock;
    int price;
};

int main()
{
    // ساخت یک متغیر از نوع Product (یک نمونه از قالب Product)
    Product p;

    // مقداردهی به اعضای Struct با عملگر نقطه (.)
    p.id = 101;
    p.name = "Rice";
    p.stock = 30;
    p.price = 120;

    // نمایش اطلاعات کالا
    cout << "Product information:\n";
    cout << "ID: " << p.id << endl;
    cout << "Name: " << p.name << endl;
    cout << "Stock: " << p.stock << endl;
    cout << "Price: " << p.price << endl;

    return 0;
}

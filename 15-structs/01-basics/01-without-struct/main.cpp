// -----------------------------------------------------------------------------
// مثال ۱: نمایش اطلاعات یک کالا (بدون استفاده از Struct)
//
// هدف آموزشی:
// - نشان دادن یک مسئله واقعی: نگهداری چند ویژگی مرتبط برای یک "کالا"
// - دیدن مشکلِ استفاده از چند متغیر جداگانه برای یک مفهوم واحد
// - آماده‌سازی ذهن دانشجو برای اینکه چرا به Struct نیاز داریم
//
// -----------------------------------------------------------------------------
// در این برنامه می‌خواهیم اطلاعات یک کالا را نگهداری و چاپ کنیم.
// هر کالا چند ویژگی دارد:
//
// - id     : شناسه کالا
// - name   : نام کالا
// - stock  : موجودی
// - price  : قیمت
//
// روش فعلی (بدون Struct):
// ما برای هر ویژگی یک متغیر جداگانه تعریف می‌کنیم.
//
// مشکل این روش چیست؟
// 1) داده‌های مربوط به یک کالا "پراکنده" می‌شوند.
// 2) اگر بخواهیم 10 کالا داشته باشیم، باید 10 بار این 4 متغیر را تکرار کنیم.
// 3) ارسال اطلاعات یک کالا به تابع سخت‌تر می‌شود (باید چند پارامتر بدهیم).
// 4) احتمال اشتباه بالا می‌رود (مثلاً قاطی شدن price یک کالا با stock کالای دیگر).
//
// در مثال بعدی همین اطلاعات را با Struct در یک قالب منسجم (Product) نگهداری می‌کنیم.
// -----------------------------------------------------------------------------

#include <iostream>
#include <string>
using namespace std;

int main()
{
    // مقداردهی به فیلدها (اینجا "فیلد" نداریم؛ فقط چند متغیر جدا داریم)
    int id = 101;
    string name = "Rice";
    int stock = 30;
    int price = 120;

    // نمایش اطلاعات کالا
    cout << "Product information:\n";
    cout << "ID: " << id << endl;
    cout << "Name: " << name << endl;
    cout << "Stock: " << stock << endl;
    cout << "Price: " << price << endl;

    return 0;
}

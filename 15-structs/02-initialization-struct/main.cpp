// -----------------------------------------------------------------------------
// مثال: مقداردهی اولیه Struct با استفاده از نام اعضا (Product)
//
// هدف آموزشی:
// - تعریف Struct برای مدل‌سازی داده‌های کالا (Product)
// - یادگیری ساخت یک نمونه (Instance) از Struct
// - آشنایی با مقداردهی اولیه (Initialization) در لحظه‌ی ساخت متغیر
// - مقایسه‌ی مقداردهی با «نام عضو» و مقداردهی «ترتیبی»
//
// -----------------------------------------------------------------------------
// ایده‌ی اصلی Struct:
// به جای اینکه اطلاعات یک کالا را در چند متغیر جدا نگه داریم، همه‌ی ویژگی‌های کالا را
// داخل یک ساختار (Struct) قرار می‌دهیم تا داده‌ها منظم‌تر و قابل‌مدیریت‌تر شوند.
//
// -----------------------------------------------------------------------------
// دو روش رایج برای مقداردهی Product:
//
// روش 1) مقداردهی جداگانه (بعد از ساخت):
//     Product p;
//     p.id = 101;
//     p.name = "Rice";
//     p.stock = 30;
//     p.price = 120;
//
// روش 2) مقداردهی اولیه هنگام ساخت (Initialization):
//     Product p = {...};
//
// در این فایل، روش 2 را تمرین می‌کنیم.
//
// -----------------------------------------------------------------------------
// مقداردهی با نام عضو (Designated Initializer):
//     Product p = { id: 101, name: "Rice", stock: 30, price: 120 };
//
// مزیت‌ها:
// 1) خواناتر است: دقیقاً مشخص است هر مقدار برای کدام عضو است.
// 2) ترتیب مهم نیست (اگر کامپایلر پشتیبانی کند).
// 3) احتمال جابه‌جا نوشتن مقدارها کمتر می‌شود.
//
// نکته‌ی خیلی مهم درباره استاندارد ++C:
// - این سینتکس (id: 101 و ...) در C استاندارد وجود دارد و در بعضی کامپایلرهای ++C
//   هم به صورت «گسترش» پشتیبانی می‌شود.
// - اما در همه‌ی محیط‌ها/کامپایلرهای ++C ممکن است کار نکند و ممکن است خطای کامپایل بدهد.
//
// روش استاندارد و مطمئن در ++C (پیشنهادی برای آموزش پایه):
//     Product p = {101, "Rice", 30, 120};
// یعنی مقدارها را دقیقاً به ترتیب تعریف اعضا در struct وارد می‌کنیم.
//
// -----------------------------------------------------------------------------
// نکته‌ی توسعه‌پذیری:
// اگر بعداً عضو جدیدی به Product اضافه کنیم (مثلاً category)، در مقداردهی ترتیبی باید
// حواسمان به ترتیب و تعداد مقدارها باشد.
// -----------------------------------------------------------------------------

#include <iostream>
#include <string>
using namespace std;

// تعریف ساختار کالا: قالبی برای نگهداری اطلاعات مربوط به یک Product
struct Product
{
    int id;      // شناسه کالا
    string name; // نام کالا
    int stock;   // موجودی کالا
    int price;   // قیمت کالا
};

int main()
{
    // ساخت و مقداردهی اولیه با نام اعضا (ممکن است در برخی کامپایلرها خطا بدهد)
    Product p = {id : 101, name : "Rice", stock : 30, price : 120};

    // روش استاندارد و قابل اعتماد:
    // Product p = {101, "Rice", 30, 120};

    // روش جایگزین (مقداردهی جداگانه):
    // p.id = 101;
    // p.name = "Rice";
    // p.stock = 30;
    // p.price = 120;

    // نمایش اطلاعات کالا
    cout << "Product information:\n";
    cout << "ID: " << p.id << "\n";
    cout << "Name: " << p.name << "\n";
    cout << "Stock: " << p.stock << "\n";
    cout << "Price: " << p.price << "\n";

    return 0;
}

// -----------------------------------------------------------------------------
// مثال: آرایه‌ای از Structها (مفهوم لایه‌بندی داده‌ها در حافظه)
//
// هدف آموزشی:
// - یادگیری روش تعریف آرایه‌ای از ساختارها (Array of Structs).
// - درک این نکته که هر خانه از آرایه، خودش یک شیءِ کامل با تمام فیلدهاست.
// - یادگیری نحوه دسترسی مستقیم به اعضای یک خانه مشخص از آرایه (با اپراتور نقطه).
//
// -----------------------------------------------------------------------------
// یک ساده‌سازی ذهنی برای دانشجو:
// در درس‌های قبل دیدیم که یک آرایه معمولی مثل int arr[2]، فقط دو عدد صحیح نگه می‌دارد.
// اما وقتی می‌نویسیم Product items[2]، یعنی آرایه‌ای داریم که دو خانه دارد و در هر
// خانه آن، یک کلاه‌خود یا جعبه‌ی کامل به نام Product قرار گرفته است.
//
// یعنی:
// - items[0] خودش به تنهایی یک Product کامل (شامل id, name, stock, price) است.
// - items[1] هم یک Product کامل دیگر است.
//
// برای دسترسی به محتویات هر خانه، ابتدا اندیس آرایه را می‌آوریم و سپس نقطه می‌زنیم:
// items[1].name
// -----------------------------------------------------------------------------

#include <iostream>
#include <string>
using namespace std;

// تعریف ساختار کالا
struct Product
{
    int id;
    string name;
    int stock;
    int price;
};

int main()
{
    // تعریف یک آرایه ۲ تایی از نوع ساختار Product
    // هر خانه به صورت مجزا با مقادیر اولیه پر می‌شود
    Product items[2] = {
        {101, "Rice", 30, 120}, // خانه صفرم: items[0]
        {102, "Oil", 20, 250}   // خانه اول:  items[1]
    };

    // دسترسی مستقیم و بدون پیچیدگیِ حلقه به اعضای خانه دوم (اندیس 1)
    // هدف: تمرکز کامل دانشجو روی ترکیب سینتکس آرایه [ ] و ساختار (.)
    cout << "Product Name: " << items[1].name << "\n";
    cout << "Product Stock: " << items[1].stock << "\n";
    cout << "Product Price: " << items[1].price << "\n";

    return 0;
}
// -----------------------------------------------------------------------------
// مثال: ثبت سفارش و نمایش لیست سفارش‌ها
//
// هدف آموزشی:
// - اتصال چند مبحث قبلی در یک برنامه منسجم
// - دریافت اطلاعات سفارش از کاربر
// - جست‌وجوی کالا بر اساس شناسه
// - کاهش موجودی کالا در صورت کافی بودن stock
// - ذخیره سفارش در آرایه سفارش‌ها
// - نمایش لیست سفارش‌های ثبت‌شده
//
// -----------------------------------------------------------------------------
// در این برنامه چند مفهوم مهم با هم ترکیب شده‌اند:
//
// 1) ساختار Product برای نگهداری اطلاعات کالا
// 2) ساختار Date برای نگهداری تاریخ
// 3) ساختار Order برای نگهداری اطلاعات سفارش
// 4) جست‌وجو در آرایه کالاها با استفاده از id
// 5) کاهش موجودی در صورت ثبت موفق سفارش
// 6) ذخیره سفارش در آرایه orders
//
// این مثال شبیه‌سازی ساده‌ای از یک سیستم ثبت سفارش است.
// -----------------------------------------------------------------------------

#include <iostream>
#include <string>
#include <iomanip>
using namespace std;

// -----------------------------------------------------------------------------
// ساختار کالا
//
// اطلاعات اصلی هر کالا:
// - id    : شناسه کالا
// - name  : نام کالا
// - stock : موجودی انبار
// - price : قیمت
// -----------------------------------------------------------------------------
struct Product
{
    int id;
    string name;
    int stock;
    int price;
};

// -----------------------------------------------------------------------------
// ساختار تاریخ
//
// برای نگهداری تاریخ سفارش
// -----------------------------------------------------------------------------
struct Date
{
    int year, month, day;
};

// -----------------------------------------------------------------------------
// ساختار سفارش
//
// اطلاعات موردنیاز برای ثبت یک سفارش:
// - customerName : نام مشتری
// - productId    : شناسه کالای سفارش‌داده‌شده
// - quantity     : تعداد سفارش
// - date         : تاریخ سفارش
// -----------------------------------------------------------------------------
struct Order
{
    string customerName;
    int productId;
    int quantity;
    Date date;
};

// -----------------------------------------------------------------------------
// تابع جست‌وجوی کالا بر اساس id
//
// ورودی‌ها:
// - items : آرایه کالاها
// - n     : تعداد کالاها
// - id    : شناسه موردنظر
//
// خروجی:
// - اگر کالا پیدا شود: اندیس آن در آرایه
// - اگر پیدا نشود: 1-
// -----------------------------------------------------------------------------
int findProductIndexById(const Product items[], int n, int id)
{
    for (int i = 0; i < n; i++)
    {
        if (items[i].id == id)
            return i;
    }
    return -1;
}

// -----------------------------------------------------------------------------
// تابع کاهش موجودی کالا
//
// اگر qty معتبر باشد و موجودی کافی باشد:
// - موجودی کم می‌شود
// - true برمی‌گردد
//
// در غیر این صورت:
// - false برمی‌گردد
// -----------------------------------------------------------------------------
bool reduceStock(Product &p, int qty)
{
    if (qty <= 0)
        return false;

    if (p.stock >= qty)
    {
        p.stock -= qty;
        return true;
    }

    return false;
}

// -----------------------------------------------------------------------------
// تابع نمایش لیست سفارش‌ها
//
// ورودی‌ها:
// - orders     : آرایه سفارش‌ها
// - orderCount : تعداد سفارش‌های ثبت‌شده
//
// این تابع همه سفارش‌ها را به صورت جدولی نمایش می‌دهد.
// -----------------------------------------------------------------------------
void printOrders(const Order orders[], int orderCount)
{
    cout << "\n=== Orders ===\n";
    cout << left << setw(15) << "Customer"
         << setw(10) << "ProdID"
         << setw(8) << "Qty"
         << "Date\n";

    for (int i = 0; i < orderCount; i++)
    {
        cout << left << setw(15) << orders[i].customerName
             << setw(10) << orders[i].productId
             << setw(8) << orders[i].quantity
             << orders[i].date.year << "/"
             << orders[i].date.month << "/"
             << orders[i].date.day << endl;
    }
}

// -----------------------------------------------------------------------------
// تابع دریافت اطلاعات سفارش از کاربر
//
// این تابع یک سفارش را از ورودی می‌گیرد و برمی‌گرداند.
// -----------------------------------------------------------------------------
Order readOrderFromUser()
{
    Order o;

    cout << "Customer name: ";
    cin >> o.customerName;

    cout << "Product id: ";
    cin >> o.productId;

    cout << "Quantity: ";
    cin >> o.quantity;

    cout << "Date (yyyy mm dd): ";
    cin >> o.date.year >> o.date.month >> o.date.day;

    return o;
}

int main()
{
    // آرایه کالاهای موجود در انبار
    const int N = 5;
    Product items[N] = {
        {101, "Rice", 30, 120},
        {102, "Oil", 20, 250},
        {103, "Sugar", 25, 110},
        {104, "Tea", 15, 300},
        {105, "Milk", 40, 90}};

    // آرایه سفارش‌ها
    const int MAX_ORDERS = 100;
    Order orders[MAX_ORDERS];
    int orderCount = 0;

    // دریافت یک سفارش از کاربر
    Order o = readOrderFromUser();

    // پیدا کردن کالای موردنظر در انبار
    int idx = findProductIndexById(items, N, o.productId);

    // اگر کالا پیدا نشد
    if (idx == -1)
    {
        cout << "Product not found.\n";
    }
    // اگر موجودی کافی نبود یا تعداد نامعتبر بود
    else if (!reduceStock(items[idx], o.quantity))
    {
        cout << "Not enough stock.\n";
    }
    // اگر همه چیز درست بود، سفارش ثبت می‌شود
    else
    {
        orders[orderCount++] = o;
        cout << "Order registered successfully.\n";
    }

    // نمایش سفارش‌های ثبت‌شده
    printOrders(orders, orderCount);

    return 0;
}

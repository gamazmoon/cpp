// -----------------------------------------------------------------------------
// مثال: آرایه‌ای از Structها برای نگهداری موجودی انبار
//
// هدف آموزشی:
// - یادگیری ساخت آرایه‌ای از Structها
// - درک این نکته که هر خانه از آرایه می‌تواند یک "کالا" باشد
// - نمایش اطلاعات چند کالا با استفاده از حلقه
//
// -----------------------------------------------------------------------------
// در مثال قبلی فقط یک کالا داشتیم و آن را در یک متغیر از نوع Product نگهداری کردیم.
// اما در برنامه‌های واقعی معمولاً با چند کالا سروکار داریم.
//
// برای مثال:
// - برنج
// - روغن
// - شکر
// - چای
// - شیر
//
// اگر بخواهیم برای هر کالا یک متغیر جدا تعریف کنیم، مدیریت برنامه سخت می‌شود.
// به همین دلیل از "آرایه‌ای از Structها" استفاده می‌کنیم.
//
// در این برنامه:
//
// - هر عضو آرایه items یک کالا از نوع Product است
// - یعنی items[0] یک Product کامل است
// - items[1] هم یک Product کامل است
// - و به همین شکل تا آخر
//
// این روش باعث می‌شود بتوانیم موجودی انبار را به صورت منظم و قابل توسعه نگهداری کنیم.
// -----------------------------------------------------------------------------

#include <iostream>
#include <string>
#include <iomanip>

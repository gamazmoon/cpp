// -----------------------------------------------------------------------------
// مثال: ارسال Struct به تابع و کاهش موجودی کالا
//
// هدف آموزشی:
// - یادگیری ارسال یک Struct به تابع
// - آشنایی با Reference برای اعمال تغییر روی متغیر اصلی
// - پیاده‌سازی یک سناریوی واقعی: کاهش موجودی پس از سفارش
//
// -----------------------------------------------------------------------------
// در درس‌های قبل:
//
// - یاد گرفتیم Struct چیست
// - یاد گرفتیم چگونه چند کالا را در آرایه‌ای از Structها نگهداری کنیم
//
// حالا می‌خواهیم یک کار عملی‌تر انجام دهیم:
// فرض کنید مشتری می‌خواهد تعدادی از یک کالا را سفارش بدهد.
// برنامه باید بررسی کند:
//
// 1) آیا تعداد واردشده معتبر است؟
// 2) آیا موجودی کالا کافی است؟
//
// اگر پاسخ هر دو سؤال "بله" باشد:
// - سفارش پذیرفته می‌شود
// - موجودی کالا کم می‌شود
//
// اگر نه:
// - سفارش رد می‌شود
//
// نکته بسیار مهم:
// تابع reduceStock باید روی خودِ کالا تغییر ایجاد کند.
// بنابراین Product را با Reference می‌فرستیم:
//
// Product &p
//
// اگر & را حذف کنیم، فقط یک کپی از کالا وارد تابع می‌شود
// و تغییرات روی نسخه اصلی اعمال نخواهد شد.
// -----------------------------------------------------------------------------

#include <iostream>
#include <string>
using namespace std;

// تعریف ساختار کالا
struct Product
{
    int id;
    string name;
    int stock;
    int price;
};

// -----------------------------------------------------------------------------
// تابع کاهش موجودی کالا
//
// ورودی‌ها:
// - p   : کالا (با Reference ارسال شده تا تغییر واقعی روی آن انجام شود)
// - qty : تعداد درخواستی
//
// خروجی:
// - اگر سفارش معتبر باشد و موجودی کافی باشد => true
// - در غیر این صورت => false
// -----------------------------------------------------------------------------
bool reduceStock(Product &p, int qty)
{
    // اگر تعداد واردشده صفر یا منفی باشد، سفارش نامعتبر است
    if (qty <= 0)
        return false;

    // اگر موجودی کالا کافی باشد، مقدار سفارش از موجودی کم می‌شود
    if (p.stock >= qty)
    {
        p.stock -= qty;
        return true;
    }

    // در غیر این صورت، سفارش رد می‌شود
    return false;
}

int main()
{
    // تعریف یک کالا
    Product p = {101, "Rice", 30, 120};

    int qty;

    // دریافت تعداد سفارش از کاربر
    cout << "Enter quantity to order: ";
    cin >> qty;

    // بررسی نتیجه سفارش
    if (reduceStock(p, qty))
    {
        cout << "Order accepted.\n";
        cout << "New stock: " << p.stock << endl;
    }
    else
    {
        cout << "Order rejected.\n";
    }

    return 0;
}

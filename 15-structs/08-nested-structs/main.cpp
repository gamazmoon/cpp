// -----------------------------------------------------------------------------
// مثال: ساختارهای تو در تو (Nested Structs)
//
// هدف آموزشی:
// - یادگیری تعریف یک Struct در داخل Struct دیگر
// - آشنایی با مدل‌سازی بهتر داده‌ها
// - دسترسی به اعضای ساختار تو در تو با عملگر نقطه
//
// -----------------------------------------------------------------------------
// در پروژه‌های واقعی، بعضی اطلاعات خودشان از چند بخش تشکیل شده‌اند.
//
// برای مثال "تاریخ سفارش" فقط یک عدد ساده نیست.
// تاریخ معمولاً شامل این بخش‌هاست:
//
// - سال
// - ماه
// - روز
//
// پس بهتر است برای تاریخ، یک ساختار جداگانه تعریف کنیم.
// سپس این ساختار را داخل ساختار سفارش قرار دهیم.
//
// این کار چند مزیت دارد:
// 1) داده‌ها منظم‌تر می‌شوند
// 2) کد خواناتر می‌شود
// 3) توسعه برنامه در آینده راحت‌تر می‌شود
//
// در این مثال:
//
// - Date  -> ساختار مربوط به تاریخ
// - Order -> ساختار مربوط به سفارش
//
// ساختار Order یکی از اعضایش را از نوع Date نگه می‌دارد.
// به این حالت می‌گوییم: ساختار تو در تو (Nested Struct)
// -----------------------------------------------------------------------------

#include <iostream>
#include <string>
using namespace std;

// -----------------------------------------------------------------------------
// ساختار تاریخ
//
// این ساختار سه بخش اصلی تاریخ را نگهداری می‌کند:
// - year  : سال
// - month : ماه
// - day   : روز
// -----------------------------------------------------------------------------
struct Date
{
    int year;
    int month;
    int day;
};

// -----------------------------------------------------------------------------
// ساختار سفارش
//
// این ساختار اطلاعات یک سفارش را نگهداری می‌کند:
// - customerName : نام مشتری
// - productId    : شناسه کالا
// - quantity     : تعداد سفارش
// - date         : تاریخ سفارش (از نوع Date)
//
// توجه کنید که date خودش یک Struct است.
// -----------------------------------------------------------------------------
struct Order
{
    string customerName;
    int productId;
    int quantity;
    Date date; // ساختار تو در تو
};

int main()
{
    // تعریف یک سفارش
    Order o;

    // مقداردهی به اطلاعات اصلی سفارش
    o.customerName = "Ali";
    o.productId = 101;
    o.quantity = 2;

    // مقداردهی به فیلدهای ساختار تو در تو
    // یعنی داریم به اعضای date که از نوع Date است دسترسی پیدا می‌کنیم
    o.date.year = 2026;
    o.date.month = 5;
    o.date.day = 29;

    // نمایش اطلاعات سفارش
    cout << "Customer: " << o.customerName << "\n";
    cout << "Product ID: " << o.productId << "\n";
    cout << "Quantity: " << o.quantity << "\n";

    // نمایش تاریخ سفارش
    cout << "Date: " << o.date.year << "/"
         << o.date.month << "/"
         << o.date.day << "\n";

    return 0;
}

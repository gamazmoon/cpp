// -----------------------------------------------------------------------------
// مثال ۳: استقلال اشیاء (Objects) در Struct و مفهوم کپی حافظه
//
// هدف آموزشی:
// - درک این مفهوم که هر متغیر (شیء) ساخته شده از Struct، یک دنیای کاملاً مستقل است.
// - آشنایی با رفتار حافظه هنگام انتساب (کپی کردن) دو Struct به یکدیگر.
// - اثبات این نکته که تغییر در اعضای یک شیء، هیچ تاثیری روی اشیاء دیگر ندارد.
//
// -----------------------------------------------------------------------------
// یک اشتباه ذهنی رایج:
// برخی دانشجویان تصور می‌کنند چون دو متغیر p1 و p2 هردو از قالب Product ساخته شده‌اند،
// یا چون در جایی از کد عملیات انتساب (p2 = p1) را انجام داده‌ایم، این دو شیء به هم 
// متصل یا وابسته شده‌اند و تغییر یکی باعث تغییر دیگری می‌شود!
//
// واقعیت در حافظه کامپیوتر (RAM):
// 1) با تعریف هر شیء جدید، یک فضای اختصاصی و کاملاً مجزا در حافظه رزرو می‌شود.
// 2) عملیات انتساب (p2 = p1) یک ارتباط دایمی نیست؛ بلکه فقط یک "کپی‌برداری لحظه‌ای" 
//    از تک‌تک مقادیر داخل فیلدهای p1 به فیلدهای p2 است.
// 3) بعد از خط انتساب، مسیر زندگی این دو شیء در حافظه کاملاً از هم جدا می‌شود.
// -----------------------------------------------------------------------------

#include <iostream>
#include <string>
using namespace std;

// تعریف ساختار کالا: قالبی برای نگهداری اطلاعات مربوط به یک Product
struct Product
{
    int id;      // شناسه کالا
    string name; // نام کالا
    int stock;   // موجودی کالا
    int price;   // قیمت کالا
};

int main()
{
    // ۱) ساخت و مقداردهی اولیه شیء اول (p1)
    Product p1 = {101, "Rice", 30, 120};

    // ۲) ساخت شیء دوم (p2) و انتساب p1 به آن
    // در این لحظه، مقادیر فیلدهای p1 کپی شده و درون فیلدهای متناظر در p2 قرار می‌گیرند.
    Product p2 = p1;

    // ۳) نمایش اطلاعات هر دو شیء قبل از اعمال تغییرات
    cout << "--- Before changing p1 ---\n";
    cout << "p1 (Rice) Price: " << p1.price << " | Stock: " << p1.stock << endl;
    cout << "p2 (Rice) Price: " << p2.price << " | Stock: " << p2.stock << endl;

    // ۴) تغییر دادن مقادیر در شیء اول (p1)
    // قیمت کالا در شیء p1 گران‌تر می‌شود و موجودی آن تغییر می‌کند.
    p1.price = 150;
    p1.stock = 25;

    // ۵) نمایش مجدد اطلاعات برای بررسی استقلال اشیاء در حافظه
    cout << "\n--- After changing p1 ---\n";
    cout << "p1 (Rice) Price: " << p1.price << " | Stock: " << p1.stock << "  <- (Changed)\n";
    cout << "p2 (Rice) Price: " << p2.price << " | Stock: " << p2.stock << "  <- (NOT Changed!)\n";

    return 0;
}
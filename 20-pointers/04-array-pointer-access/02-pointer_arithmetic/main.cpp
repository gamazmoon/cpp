// -----------------------------------------------------------------------------
// مثال محاسبات اشاره‌گری (Pointer Arithmetic) در ++C
// این برنامه یک مثال آموزشی برای آشنایی با حرکت روی عناصر آرایه
// با استفاده از محاسبات اشاره‌گری در زبان ++C است.
//
// هدف آموزشی مثال:
// - آشنایی با Pointer Arithmetic.
// - دسترسی به عناصر آرایه با استفاده از عملگر *.
// - حرکت روی حافظه با استفاده از اشاره‌گر.
// - تغییر مقدار عناصر آرایه از طریق اشاره‌گر.
//
// شرح عملکرد برنامه:
//
// 1. تعریف آرایه:
//
//        int x[3] = {12, 2, 5};
//
//    یک آرایه از سه عدد صحیح ایجاد می‌شود.
//
// 2. تعریف اشاره‌گر:
//
//        int *p = x;
//
//    اشاره‌گر p به اولین عنصر آرایه اشاره می‌کند.
//
// 3. دسترسی به عناصر با Dereference:
//
//        *(p)
//        *(p + 1)
//        *(p + 2)
//
//    در این عبارات:
//
//    - p آدرس اولین عنصر آرایه است.
//    - p + 1 یعنی حرکت به عنصر بعدی.
//    - p + 2 یعنی حرکت دو خانه جلوتر.
//    - عملگر * مقدار آن آدرس را استخراج می‌کند.
//
// 4. تغییر مقدار عنصر دوم:
//
//        *(p + 1) = 100;
//
//    این دستور مقدار عنصر دوم آرایه را تغییر می‌دهد.
//
//    بنابراین مقدار:
//
//        x[1]
//
//    برابر 100 خواهد شد.
//
// نکات آموزشی:
// - عملگر + روی اشاره‌گرها بر اساس اندازه‌ی نوع داده عمل می‌کند.
// - محاسبات اشاره‌گری امکان حرکت بین عناصر آرایه را فراهم می‌کند.
// - عبارت‌های زیر معادل هستند:
//
//        x[2]
//        p[2]
//        *(p + 2)
//
// این مفهوم در مباحث پیشرفته‌تر مانند:
// - پیمایش آرایه‌ها
// - مدیریت حافظه
// - ساختمان داده‌ها
// - کار با رشته‌ها
// کاربرد زیادی دارد.
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    int x[3] = {12, 2, 5};

    int *p = x;

    cout << *(p);
    cout << "\n";

    cout << *(p + 1);
    cout << "\n";

    cout << *(p + 2);
    cout << "\n";

    *(p + 1) = 100;

    cout << x[1];

    return 0;
}

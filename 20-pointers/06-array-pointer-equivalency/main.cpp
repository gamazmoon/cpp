// -----------------------------------------------------------------------------
// مثال بررسی معادل بودن آرایه و اشاره‌گر در ++C
// این برنامه یک مثال آموزشی برای درک رابطه‌ی بین آرایه و اشاره‌گر
// در زبان ++C است.
//
// هدف آموزشی مثال:
// - درک ارتباط آرایه و اشاره‌گر.
// - آشنایی با آدرس عناصر آرایه.
// - آشنایی با Pointer Arithmetic.
// - درک معادل بودن دسترسی آرایه‌ای و اشاره‌گری.
//
// شرح عملکرد برنامه:
//
// 1. تعریف آرایه:
//
//        int x[3] = {12, 2, 5};
//
//    یک آرایه شامل سه عدد صحیح ایجاد می‌شود.
//
// 2. تعریف اشاره‌گر:
//
//        int *p = x;
//
//    نام آرایه در بسیاری از عبارات به آدرس اولین عنصر آن تبدیل می‌شود.
//    بنابراین p به اولین عنصر آرایه اشاره می‌کند.
//
// 3. مقایسه‌ی آدرس‌ها:
//
//        &(x[0]) == (p + 0);
//        &(x[1]) == (p + 1);
//        &(x[2]) == (p + 2);
//
//    در این عبارات:
//
//    - &(x[i]) آدرس عنصر iام آرایه را برمی‌گرداند.
//    - (p + i) نیز آدرس همان عنصر را تولید می‌کند.
//
//    بنابراین این عبارت‌ها مقدار true خواهند داشت.
//
// 4. مقایسه‌ی مقدارها:
//
//        x[0] == *(p);
//        x[1] == *(p + 1);
//        x[2] == *(p + 2);
//
//    در این بخش:
//
//    - x[i] مقدار عنصر iام آرایه است.
//    - *(p + i) مقدار موجود در همان آدرس را استخراج می‌کند.
//
//    بنابراین این عبارت‌ها نیز true هستند.
//
// مفهوم مهم:
//
//        x[i]        == *(p + i)
//        &(x[i])     == (p + i)
//
// این رابطه یکی از مهم‌ترین مفاهیم اشاره‌گرها در ++C است.
//
// نکات آموزشی:
// - نام آرایه به آدرس اولین عنصر آن تبدیل می‌شود.
// - اشاره‌گرها می‌توانند مانند آرایه‌ها برای دسترسی به داده‌ها استفاده شوند.
// - Pointer Arithmetic بر اساس اندازه‌ی نوع داده انجام می‌شود.
// - آرایه و اشاره‌گر ارتباط بسیار نزدیکی با یکدیگر دارند.
//
// این مفهوم در مباحث زیر کاربرد زیادی دارد:
// - پیمایش آرایه‌ها
// - ارسال آرایه به توابع
// - مدیریت حافظه
// - ساختمان داده‌ها
// - پردازش رشته‌ها
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    int x[3] = {12, 2, 5};
    int *p = x;

    &(x[0]) == (p + 0);
    &(x[1]) == (p + 1);
    &(x[2]) == (p + 2);

    x[0] == *(p);
    x[1] == *(p + 1);
    x[2] == *(p + 2);

    return 0;
}

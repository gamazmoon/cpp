// -----------------------------------------------------------------------------
// مثال تعریف و مقداردهی اولیه اشاره‌گرها در ++C
// این برنامه یک مثال آموزشی برای آشنایی با «اشاره‌گرها» (Pointers) در زبان ++C است.
//
// هدف آموزشی مثال:
// - درک مفهوم اشاره‌گر به عنوان متغیری که آدرسِ حافظه‌ی متغیر دیگری را نگه می‌دارد.
// - آشنایی با نحوه‌ی تعریف اشاره‌گر برای انواع داده‌های مختلف (int, double, char, long).
// - استفاده از عملگر & برای به دست آوردن آدرس و ذخیره آن در اشاره‌گر.
//
// شرح عملکرد برنامه:
//
// 1. تعریف اشاره‌گر:
//    برای تعریف اشاره‌گر، از علامت * بعد از نوع داده استفاده می‌کنیم:
//        int *p1;
//
// 2. مقداردهی اشاره‌گر:
//    برای اینکه اشاره‌گر به متغیر خاصی اشاره کند، آدرس آن متغیر را به آن اختصاص می‌دهیم:
//        int *p1 = &x;
//
// 3. در این برنامه:
//    - p1 آدرسِ یک متغیر int را نگه می‌دارد.
//    - p2 آدرسِ یک متغیر double را نگه می‌دارد.
//    - p3 آدرسِ یک متغیر char را نگه می‌دارد.
//    - p4 آدرسِ یک متغیر long را نگه می‌دارد.
//
// 4. دستور خروجی:
//        cout << p1;
//    این دستور آدرس حافظه‌ای که p1 به آن اشاره می‌کند را چاپ می‌کند (معمولاً به صورت هگزادسیمال).
//
// نکات آموزشی:
// - نوع داده‌ی اشاره‌گر باید با نوع داده‌ی متغیری که به آن اشاره می‌کند همخوانی داشته باشد
//   (مثلاً برای اشاره به یک double، باید از double* استفاده کرد).
// - علامت * در زمان تعریف متغیر، نشان‌دهنده‌ی اشاره‌گر بودن آن است.
// - اشاره‌گرها به ما اجازه می‌دهند مستقیماً با حافظه کار کنیم.
//
// این مثال پایه‌ای برای مباحث پیشرفته‌تر مانند:
// - دسترسی به مقدار متغیر از طریق اشاره‌گر (Dereferencing با استفاده از *)
// - تغییر مقدار متغیرها توسط اشاره‌گر
// - پاس دادن به توابع با اشاره‌گر
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    // اشاره‌گر به یک عدد صحیح
    int x = 10;
    int *p1 = &x;

    cout << p1; // چاپ آدرس x
    cout << "\n";

    // اشاره‌گر به یک عدد اعشاری
    double d = 14.5;
    double *p2 = &d;

    // اشاره‌گر به یک کاراکتر
    char c = 'a';
    char *p3 = &c;

    // اشاره‌گر به یک عدد صحیح بلند
    long l = 12334455;
    long* p4 = &l;

    return 0;
}

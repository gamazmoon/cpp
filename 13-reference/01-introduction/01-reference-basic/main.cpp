// -----------------------------------------------------------------------------
// مثال: معرفی Reference
//
// هدف آموزشی:
// - آشنایی با مفهوم reference در C++
// - درک اینکه reference یک نام دیگر برای یک متغیر است
//
// -----------------------------------------------------------------------------
// در C++ می‌توان برای یک متغیر، نام دیگری تعریف کرد.
// این نام جدید "reference" نام دارد.
//
// شکل کلی:
//
//      int &y = x;
//
// در اینجا y یک reference برای x است.
// یعنی y و x در واقع به یک مقدار در حافظه اشاره می‌کنند.
//
// اگر مقدار y تغییر کند، مقدار x نیز تغییر خواهد کرد.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    int x;
    x = 12;

    int &y = x;

    y = 18;

    cout << x << "\n";
    cout << y << "\n";

    return 0;
}

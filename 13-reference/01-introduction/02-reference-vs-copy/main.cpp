// -----------------------------------------------------------------------------
// مثال: تفاوت copy و reference
//
// هدف آموزشی:
// - درک تفاوت بین کپی کردن یک متغیر
// - و ساختن یک reference
//
// -----------------------------------------------------------------------------
// اگر یک متغیر را اینگونه تعریف کنیم:
//
//      int b = a;
//
// مقدار a در b کپی می‌شود.
// بنابراین تغییر b روی a تاثیری ندارد.
//
// اما اگر reference بسازیم:
//
//      int &b = a;
//
// در این حالت b فقط نام دیگری برای a است.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    int a = 10;

    int b = a; // copy

    b = 20;

    cout << "a = " << a << "\n";
    cout << "b = " << b << "\n";

    return 0;
}

// -----------------------------------------------------------------------------
// مثال: معرفی Reference
//
// هدف آموزشی:
// - آشنایی با مفهوم reference در C++
// - درک اینکه reference یک نام دیگر برای یک متغیر است
//
// -----------------------------------------------------------------------------
// در C++ می‌توان برای یک متغیر، نام دیگری تعریف کرد.
// این نام جدید "reference" نام دارد.
//
// شکل کلی:
//
//      int &r = x;
//
// در اینجا r یک reference برای x است.
// یعنی r و x در واقع به یک مقدار در حافظه اشاره می‌کنند.
//
// اگر مقدار r تغییر کند، مقدار x نیز تغییر خواهد کرد.
//
// -----------------------------------------------------------------------------

#include <iostream>
using namespace std;

int main()
{
    int x = 10;

    int &r = x;

    r = 20;

    cout << x << endl;

    return 0;
}
